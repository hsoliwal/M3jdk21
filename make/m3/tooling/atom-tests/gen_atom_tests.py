"""gen_atom_tests.py <spec_dir> <template_dir> <test_dir> <patterns_tsv> [<library_dir>] : ATOM-TEST GENERATOR v2.

The recipe for "a JUnit for every atom": one spec row per method/constructor atom names its contract
PATTERN and the arguments of that pattern; the pattern's template turns the row into one test method,
and every owner source file becomes one jtreg-compatible JUnit class <Owner>AtomTest whose
@TestFactory publishes one DynamicTest per atom. Fix a template (and add a RECIPE_MEMORY.tsv row),
never a generated file.

spec_dir      one <Owner>.atoms per owner source file:
                #class <Owner>AtomTest     #summary <text>     #build <Helper ...>     #import <type>
                #runopts </othervm ...>   #helper <<< java >>>  (class-level helper members)
                #const <type> <NAME> = <java initializer> // <role>   (a named constant of the class)
                #template <CLASS_TEMPLATE> #entry <factory> #returns <type>  (default CLASS, dynamicTest, void;
                the perf harness uses PERF_CLASS, M3AtomPerf.named, M3AtomPerf.Batch)
                @atom <Owner[.Nested]>.<atom> <n> <PATTERN> <oracle words...>
                <arg> = <one-line java>   or   <arg> <<<  multi-line java  >>>
template_dir  <PATTERN>.tmpl bodies with ${arg} placeholders, plus CLASS.tmpl. Leading '## ' lines are template
              metadata and are not rendered: '## optional <arg>...' names arguments that default to empty.
test_dir      output directory of the generated classes.
patterns_tsv  TEST_PATTERNS.tsv (atom, pattern, test, oracle) written for the whole spec set.
library_dir   directory of the hand-written test library (M3AtomKit, the oracles); default test_dir.

v2 gates (every refusal of the whole run is listed, then exit status 1 and nothing is written):
  ASSERTION GATE v2  a rendered body must call a JUnit assertion (assert*/fail of org.junit.jupiter.api.Assertions)
                     or an oracle comparison helper: an assert*/expect*/check*-named method of the test library or of
                     the spec's #helper block whose body, catch blocks removed, calls a JUnit assertion, throws
                     AssertionError or calls another oracle comparison helper (fixed point). Lookup helpers
                     (findStatic & co.) and unverified XxxOracle/check* calls do not count.
  LITERAL GATE v1    no numeric literal outside a named constant in a rendered body, a #helper block or the test
                     library: dispositions of LITERAL_CONSTANTS v1.1 (EXEMPT_UNIT 0/1 with unary minus, CONSTANT_DEF
                     and TABLE_DATA inside a static final field declaration, ANNOTATION_ARG); every other literal must
                     be a #const (or a static final of the helper block).
  plus duplicate rows, unknown patterns, missing arguments, helper/atom name clashes and #const hygiene (UPPER_CASE,
  unique, documented, referenced)."""
import os
import re
import string
import sys

GENERATED = "// GENERATED by make/m3/tooling/atom-tests/gen_atom_tests.py from specs/{spec}; edit the spec or template."
GENERATED_PREFIX = GENERATED.split(" from ")[0]
INDENT = "        "
MEMBER_INDENT = "    "
OPTIONAL_ARGS = ("setup", "extra")
TEMPLATE_META = "## "
TEMPLATE_OPTIONAL = "optional"
# A static no-argument test method cannot take the name of an Object instance method.
OBJECT_METHODS = {"equals", "hashCode", "toString", "getClass", "notify", "notifyAll", "wait", "clone", "finalize"}

# ---- ASSERTION GATE v2 ------------------------------------------------------------------------------------------
#FLLDCIM: TOP - ASSERTION GATE v2: a real JUnit assertion or a verified oracle comparison helper (finding b, #2251)
JUNIT_CLASS = "Assertions"
JUNIT_ASSERTIONS = frozenset((
    "assertAll", "assertArrayEquals", "assertDoesNotThrow", "assertEquals", "assertFalse", "assertInstanceOf",
    "assertIterableEquals", "assertLinesMatch", "assertNotEquals", "assertNotNull", "assertNotSame", "assertNull",
    "assertSame", "assertThrows", "assertThrowsExactly", "assertTimeout", "assertTimeoutPreemptively", "assertTrue",
    "fail"))
COMPARISON_PREFIXES = ("assert", "expect", "check")
THROW_ASSERTION = re.compile(r"\bthrow\s+new\s+AssertionError\b")
CALL = re.compile(r"(?<![\w$.])(?:([A-Z][\w$]*)\s*\.\s*)?([a-z_$][\w$]*)\s*\(")
CATCH = re.compile(r"\bcatch\s*\([^)]*\)\s*\{")
MEMBER_METHOD = re.compile(
    r"(?m)^    (?:(?:public|private|protected|static|final|synchronized)\s+)*(?:<[^>\n]*>\s+)?"
    r"[\w<>\[\]?,. ]+?\s([a-z_$][\w$]*)\s*\(([^)]*)\)\s*(?:throws\s+[\w.,\s]+?)?\s*\{")
# The assertion test of v1, kept only to report which rows it accepted that v2 refuses.
V1_ASSERTION = re.compile(r"\bassert[A-Z]\w*\(|\bexpect(Message)?\(|\bfail\(|Oracle\.\w+|\bcheck\w*\(")

# ---- LITERAL GATE v1 (dispositions of LITERAL_CONSTANTS v1.1) ----------------------------------------------------
#FLLDCIM: SFA - LITERAL GATE v1: numeric literals live in named constants (finding a, #2251; LITERAL_CONSTANTS v1.1)
MASK = re.compile(r'//[^\n]*|/\*.*?\*/|"""(?:\\.|[^\\])*?"""|"(?:\\.|[^"\\\n])*"|\'(?:\\.|[^\'\\\n])+\'', re.S)
NUMBER = re.compile(r"(?<![\w$.])(0[xX][0-9a-fA-F_]+[lL]?|0[bB][01_]+[lL]?"
                    r"|(?:\d[\d_]*\.\d*|\.\d+)(?:[eE][+-]?\d+)?[fFdD]?|\d[\d_]*(?:[eE][+-]?\d+)?[lLfFdD]?)(?![\w$])")
STATIC_FINAL = re.compile(r"\bstatic\s+final\b")
ANNOTATION_ARGS = re.compile(r"@[A-Za-z_$][\w$.]*\s*\(")
UNIT_VALUES = (0, 1)
CONST = re.compile(r"^([\w<>\[\]?, .]+?)\s+([A-Za-z_$][\w$]*)\s*=\s*(.+?)\s*//\s*(.*\S)\s*$")
CONST_NAME = re.compile(r"^[A-Z][A-Z0-9_]*$")


def mask(text):
    """Comments, strings, text blocks and chars become blanks (newlines kept), so offsets stay valid."""
    return MASK.sub(lambda m: re.sub(r"[^\n]", " ", m.group(0)), text)


def balanced_end(text, open_at, opening="{", closing="}"):
    """Offset just after the bracket closing the one at open_at (text is masked)."""
    depth = 0
    for i in range(open_at, len(text)):
        if text[i] == opening:
            depth += 1
        elif text[i] == closing:
            depth -= 1
            if depth == 0:
                return i + 1
    return len(text)


def strip_catch_blocks(masked):
    """Removes catch clauses: an AssertionError raised while handling a lookup failure is not a comparison."""
    out = masked
    m = CATCH.search(out)
    while m:
        end = balanced_end(out, m.end() - 1)
        out = out[:m.start()] + out[end:]
        m = CATCH.search(out)
    return out


def member_methods(source):
    """name -> [body] of the member methods (4-space indent) of a class source or a #helper block."""
    masked = mask(source)
    out = {}
    for m in MEMBER_METHOD.finditer(masked):
        end = balanced_end(masked, m.end() - 1)
        out.setdefault(m.group(1), []).append(masked[m.end():end - 1])
    return out


def calls(masked_body):
    return [(q, n) for q, n in CALL.findall(masked_body)]


def is_junit_assertion(qualifier, name):
    return name in JUNIT_ASSERTIONS and qualifier in ("", JUNIT_CLASS)


class AssertionCatalog:
    """Oracle comparison helpers of the test library (Class.method) and of one #helper block (method)."""

    def __init__(self, sources):
        """sources: class simple name -> source text of the hand-written test library."""
        self.library = {}
        for owner, source in sorted(sources.items()):
            for method, bodies in member_methods(source).items():
                self.library[owner + "." + method] = (owner, bodies)
        self.library_verified = self._fixed_point(self.library, set(self.library), set())

    @classmethod
    def from_dir(cls, library_dir):
        return cls(library_sources(library_dir))

    @staticmethod
    def _target(qualifier, name, owner):
        """Helper key a call names: Class.method when qualified or inside a library class, else a #helper method."""
        if qualifier:
            return qualifier + "." + name
        return owner + "." + name if owner else name

    def _asserts(self, masked_bodies, owner, defined, known):
        """True when one of the bodies calls a JUnit assertion, throws AssertionError or calls a known helper."""
        for body in masked_bodies:
            stripped = strip_catch_blocks(body)
            if THROW_ASSERTION.search(stripped):
                return True
            for q, n in calls(stripped):
                target = self._target(q, n, owner)
                if target in known or (is_junit_assertion(q, n) and target not in defined):
                    return True
        return False

    def _fixed_point(self, table, defined, seed):
        known = set(seed)
        changed = True
        while changed:
            changed = False
            for key, (owner, bodies) in table.items():
                if key in known or not key.rsplit(".", 1)[-1].startswith(COMPARISON_PREFIXES):
                    continue
                if self._asserts(bodies, owner, defined, known):
                    known.add(key)
                    changed = True
        return known

    def local_scope(self, helpers_source):
        """(verified helper keys, defined helper keys) of one class: the library plus its #helper block."""
        local = {name: (None, bodies) for name, bodies in member_methods(helpers_source).items()}
        defined = set(self.library) | set(local)
        return self._fixed_point(local, defined, self.library_verified), defined

    def body_asserts(self, body, scope):
        verified, defined = scope
        return self._asserts([mask(body)], None, defined, verified)


def literal_hoists(source):
    """(offset, literal) of every numeric literal that is not EXEMPT_UNIT, CONSTANT_DEF/TABLE_DATA or ANNOTATION_ARG."""
    masked = mask(source)
    exempt = []
    for m in STATIC_FINAL.finditer(masked):
        depth, end = 0, len(masked)
        for i in range(m.end(), len(masked)):
            c = masked[i]
            if c in "([{":
                depth += 1
            elif c in ")]}":
                depth -= 1
            elif c == ";" and depth == 0:
                end = i
                break
        exempt.append((m.start(), end))
    for m in ANNOTATION_ARGS.finditer(masked):
        exempt.append((m.start(), balanced_end(masked, m.end() - 1, "(", ")")))
    out = []
    for m in NUMBER.finditer(masked):
        if any(s <= m.start() < e for s, e in exempt):
            continue
        if numeric_value(m.group(1)) in UNIT_VALUES:
            continue
        out.append((m.start(), m.group(1)))
    return out


def numeric_value(text):
    t = text.replace("_", "").lower()
    try:
        if t.startswith("0x"):
            return int(t[2:].rstrip("l"), 16)
        if t.startswith("0b"):
            return int(t[2:].rstrip("l"), 2)
        if any(c in t for c in ".e") or t.endswith(("f", "d")):
            return float(t.rstrip("fd"))
        body = t.rstrip("l")
        return int(body, 8) if len(body) > 1 and body.startswith("0") else int(body)
    except ValueError:
        return None


def line_of(source, offset):
    start = source.rfind("\n", 0, offset) + 1
    end = source.find("\n", offset)
    return source[start:end if end >= 0 else len(source)].strip()


# ---- templates and specs -----------------------------------------------------------------------------------------
def load_templates(template_dir):
    """name -> (body, optional argument names); '## ' lines at the top are metadata."""
    templates = {}
    for name in sorted(os.listdir(template_dir)):
        if name.endswith(".tmpl"):
            with open(os.path.join(template_dir, name), encoding="utf-8") as f:
                lines = f.read().split("\n")
            optional = set(OPTIONAL_ARGS)
            while lines and lines[0].startswith(TEMPLATE_META):
                words = lines.pop(0)[len(TEMPLATE_META):].split()
                if words and words[0] == TEMPLATE_OPTIONAL:
                    optional.update(words[1:])
            templates[name[:-len(".tmpl")]] = ("\n".join(lines), optional)
    return templates


HEADER = re.compile(r"^#(\w+)\s*(.*)$")
ATOM = re.compile(r"^@atom\s+(\S+)\.(\w+)\s+(\d+)\s+(\w+)\s*(.*)$")
ARG = re.compile(r"^(\w+)\s*=\s?(.*)$")
BLOCK = re.compile(r"^(\w+)\s*<<<\s*$")


def parse_spec(path):
    with open(path, encoding="utf-8") as f:
        return parse_spec_text(f.read(), path)


def parse_spec_text(text, path):
    header = {"imports": [], "build": [], "helpers": [], "consts": []}
    rows, row, block, buffer = [], None, None, []
    for number, line in enumerate(text.split("\n"), 1):
        if block is not None:
            if line.strip() == ">>>":
                block_text = "\n".join(buffer)
                if row is None:
                    header[block].append(block_text) if block == "helpers" else header.__setitem__(block, block_text)
                else:
                    row["args"][block] = block_text
                block, buffer = None, []
            else:
                buffer.append(line)
            continue
        if not line.strip() or line.startswith("//"):
            continue
        m = ATOM.match(line)
        if m:
            owner, atom, n, pattern, oracle = m.groups()
            row = {"owner": owner, "atom": atom, "n": int(n), "pattern": pattern,
                   "oracle": oracle.strip() or "contract", "args": {}, "line": number}
            rows.append(row)
            continue
        m = HEADER.match(line)
        if m and row is None:
            key, value = m.groups()
            if key == "helper" and value.strip() == "<<<":
                block = "helpers"
            elif key in ("import", "build"):
                header["imports" if key == "import" else "build"].extend(value.split())
            elif key == "const":
                c = CONST.match(value)
                if not c:
                    raise SystemExit("%s:%d: #const needs '<type> <NAME> = <initializer> // <role>': %s"
                                     % (path, number, line))
                header["consts"].append({"type": c.group(1), "name": c.group(2), "value": c.group(3),
                                         "role": c.group(4), "line": number})
            else:
                header[key] = value
            continue
        m = BLOCK.match(line)
        if m and row is not None:
            block = m.group(1)
            continue
        m = ARG.match(line)
        if m and row is not None:
            row["args"][m.group(1)] = m.group(2)
            continue
        raise SystemExit("%s:%d: unparsed spec line: %s" % (path, number, line))
    if block is not None:
        raise SystemExit("%s: unterminated <<< block %s" % (path, block))
    return header, rows


def method_name(row):
    if "method" in row:
        return row["method"]
    owner = row["owner"].split(".")
    nested = "_".join(owner[1:])
    atom = "atom_" + row["atom"] if row["atom"] in OBJECT_METHODS and not nested else row["atom"]
    base = atom if not nested else nested + "_" + row["atom"]
    return base if row.get("n", 1) == 1 else "%s_%d" % (base, row["n"])


def assign_method_names(rows):
    """Names stay the atom name; only names shared by atoms of different owners get the top owner prefix."""
    counts = {}
    for row in rows:
        counts[method_name(row)] = counts.get(method_name(row), 0) + 1
    for row in rows:
        name = method_name(row)
        row["method"] = name if counts[name] == 1 else row["owner"].split(".")[0] + "_" + name


def render_body(row, templates, spec):
    pattern = row["pattern"]
    if pattern not in templates:
        raise SystemExit("unknown pattern %s in %s" % (pattern, spec))
    template, optional = templates[pattern]
    args = dict(row.get("args", {}))
    args.setdefault("atom", row["atom"])
    args.setdefault("owner", row["owner"])
    for name in optional:
        args.setdefault(name, "")
    try:
        return string.Template(template).substitute(args)
    except KeyError as missing:
        raise SystemExit("missing argument %s for %s.%s (%s)" % (missing, row["owner"], row["atom"], pattern))


def render_row(row, body, returns="void"):
    lines = [INDENT + line if line.strip() else "" for line in body.strip("\n").split("\n")]
    name = method_name(row)
    label = "%s.%s#%d %s" % (row["owner"], row["atom"], row.get("n", 1), row["pattern"])
    method = "    /** %s; oracle: %s. */\n    static %s %s() throws Throwable {\n%s\n    }\n" % (
        label, row.get("oracle", "contract"), returns, name, "\n".join(lines))
    return name, label, method


def render_constants(consts):
    if not consts:
        return ""
    lines = []
    for c in consts:
        lines.append("%s/** %s */\n%sprivate static final %s %s = %s;\n" % (
            MEMBER_INDENT, c["role"], MEMBER_INDENT, c["type"], c["name"], c["value"]))
    return "".join(lines) + "\n"


def render_class(header, rows, templates, spec, catalog, errors, audit):
    methods, entries, bodies = [], [], []
    seen = set()
    assign_method_names(rows)
    helpers = "\n".join(header.get("helpers", []))
    scope = catalog.local_scope(helpers)
    for row in rows:
        key = (row["owner"], row["atom"], row.get("n", 1))
        if key in seen:
            raise SystemExit("duplicate atom row %s in %s" % (key, spec))
        seen.add(key)
        body = render_body(row, templates, spec)
        where = "%s:%d %s.%s#%d" % (spec, row.get("line", 0), row["owner"], row["atom"], row.get("n", 1))
        v1 = bool(V1_ASSERTION.search(body))
        v2 = catalog.body_asserts(body, scope)
        audit.append((where, row["pattern"], v1, v2))
        if not v2:
            errors.append("ASSERTION %s (%s): no JUnit assertion and no verified oracle comparison helper call"
                          % (where, row["pattern"]))
        for offset, literal in literal_hoists(body):
            errors.append("LITERAL %s: %s in '%s'" % (where, literal, line_of(body, offset)))
        name, label, method = render_row(row, body, header.get("returns", "void"))
        bodies.append(body)
        methods.append(method)
        entries.append('                %s("%s", %s::%s)' % (header.get("entry", "dynamicTest"), label, header["class"], name))
    for offset, literal in literal_hoists(helpers):
        errors.append("LITERAL %s #helper: %s in '%s'" % (spec, literal, line_of(helpers, offset)))
    check_constants(header.get("consts", []), bodies + [helpers], spec, errors)
    imports = "".join("import %s;\n" % i for i in header.get("imports", []))
    for row in rows:
        declaration = r"(?m)^\s{4}(?:(?:private|static|public|final)\s+)+[\w<>\[\]?, ]+\s%s\s*\(" % method_name(row)
        if re.search(declaration, helpers):
            raise SystemExit("helper method clashes with generated atom method %s in %s" % (method_name(row), spec))
    return string.Template(templates[header.get("template", "CLASS")][0]).substitute(
        generated=GENERATED.format(spec=spec), summary=header["summary"], cls=header["class"],
        build=" ".join(header.get("build", [])), imports=imports, entries=",\n".join(entries),
        methods="\n".join(methods), helpers=helpers, runopts=header.get("runopts", ""),
        constants=render_constants(header.get("consts", [])))


def check_constants(consts, sources, spec, errors):
    names = set()
    text = mask("\n".join(sources) + "\n" + "\n".join(c["value"] for c in consts))
    for c in consts:
        where = "%s:%d #const %s" % (spec, c["line"], c["name"])
        if not CONST_NAME.match(c["name"]):
            errors.append("CONST %s: name is not UPPER_CASE" % where)
        if c["name"] in names:
            errors.append("CONST %s: declared twice" % where)
        names.add(c["name"])
        if not re.search(r"(?<![\w$.])%s(?![\w$])" % re.escape(c["name"]), text):
            errors.append("CONST %s: never referenced" % where)


def library_sources(library_dir):
    """class simple name -> source of every hand-written (not generated) .java file of the library directory."""
    sources = {}
    for name in sorted(os.listdir(library_dir)) if library_dir and os.path.isdir(library_dir) else []:
        if name.endswith(".java"):
            with open(os.path.join(library_dir, name), encoding="utf-8") as f:
                source = f.read()
            if GENERATED_PREFIX not in source:
                sources[name[:-len(".java")]] = source
    return sources


def library_literal_errors(sources):
    errors = []
    for owner, source in sorted(sources.items()):
        for offset, literal in literal_hoists(source):
            line = source.count("\n", 0, offset) + 1
            errors.append("LITERAL %s.java:%d (library): %s in '%s'" % (owner, line, literal, line_of(source, offset)))
    return errors


def main():
    spec_dir, template_dir, test_dir, patterns_tsv = sys.argv[1:5]
    library_dir = sys.argv[5] if len(sys.argv) > 5 else test_dir
    templates = load_templates(template_dir)
    sources = library_sources(library_dir)
    catalog = AssertionCatalog(sources)
    errors, audit, outputs, rows_out = library_literal_errors(sources), [], [], []
    for spec in sorted(os.listdir(spec_dir)):
        if not spec.endswith(".atoms"):
            continue
        header, rows = parse_spec(os.path.join(spec_dir, spec))
        source = render_class(header, rows, templates, spec, catalog, errors, audit)
        outputs.append((os.path.join(test_dir, header["class"] + ".java"), source, header["class"], len(rows)))
        for row in rows:
            rows_out.append((row["owner"] + "." + row["atom"] + "#" + str(row.get("n", 1)), row["pattern"],
                             header["class"] + "." + method_name(row), row.get("oracle", "contract")))
    v1_only = [a for a in audit if a[2] and not a[3]]
    print("assertion_gate v1_accepts=%d v2_accepts=%d v1_only=%d rows=%d"
          % (sum(1 for a in audit if a[2]), sum(1 for a in audit if a[3]), len(v1_only), len(audit)))
    if errors:
        for e in errors:
            print(e)
        print("refused=%d (nothing written)" % len(errors))
        sys.exit(1)
    for path, source, cls, count in outputs:
        with open(path, "w", encoding="utf-8", newline="\n") as w:
            w.write(source)
        print("%s atoms=%d" % (cls, count))
    with open(patterns_tsv, "w", encoding="utf-8", newline="\n") as w:
        w.write("atom\tpattern\ttest\toracle\n")
        w.writelines("\t".join(r) + "\n" for r in rows_out)
    print("generated_atoms=%d" % len(rows_out))


if __name__ == "__main__":
    main()
