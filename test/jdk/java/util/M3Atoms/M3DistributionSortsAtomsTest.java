    enum Shape { RANDOM, FEW, ASCENDING, DESCENDING, EQUAL, ORGAN_PIPE, SAWTOOTH }

    /** Deterministic key vector for one (length, shape) pair. */
    static int[] keys(int n, Shape shape) {
        Random r = new Random(SEED ^ ((long) n << Integer.SIZE) ^ shape.ordinal());
        return IntStream.range(0, n).map(i -> switch (shape) {
            case RANDOM -> r.nextInt(WIDE) - WIDE / 2;
            case FEW -> r.nextInt(FEW_DISTINCT);
            case ASCENDING -> i;
            case DESCENDING -> n - i;
            case EQUAL -> 0;
            case ORGAN_PIPE -> Math.min(i, n - 1 - i);
            case SAWTOOTH -> i % SAWTOOTH_PERIOD;
        }).toArray();
    }

    interface VectorCheck {
        void check(int[] keys, int[] labels) throws Throwable;
    }

    /** Runs {@code check} over every (size, shape) vector whose length is at least {@code minLength}. */
    static void forEachVector(int minLength, VectorCheck check) throws Throwable {
        for (int n : SIZES) {
            if (n >= minLength) {
                for (Shape s : Shape.values()) {
                    check.check(keys(n, s), identity(n));
                }
            }
        }
    }

    static int[] identity(int n) {
        return IntStream.range(0, n).toArray();
    }

    /** A borrowed M3SortContext comparing labels by {@code keys[label]}, without a monitor. */
    static Object context(int[] keys) throws Throwable {
        IntBinaryOperator byKey = (x, y) -> Integer.compare(keys[x], keys[y]);
        return NEW_CONTEXT.invoke(byKey, (ProgressMonitor) null);
    }

    /** A context over long keys addressed as {@code keys[index - base]}. */
    static Object longContext(long[] keys, int base) throws Throwable {
        IntBinaryOperator byKey = (x, y) -> Long.compare(keys[x - base], keys[y - base]);
        return NEW_CONTEXT.invoke(byKey, (ProgressMonitor) null);
    }

    /** JDK differential: [lo, hi) stably ordered by key (java.util.Arrays.sort over objects is stable). */
    static int[] stableOrder(int[] keys, int[] labels, int lo, int hi) {
        Integer[] boxed = IntStream.of(labels).boxed().toArray(Integer[]::new);
        Arrays.sort(boxed, lo, hi, Comparator.comparingInt(l -> keys[l]));
        return Stream.of(boxed).mapToInt(Integer::intValue).toArray();
    }

    static int[] keysAlong(int[] keys, int[] labels, int lo, int hi) {
        return IntStream.range(lo, hi).map(i -> keys[labels[i]]).toArray();
    }

    /** Sorted-permutation contract; stable kernels must equal the stable JDK order exactly. */
    static void assertSortedPermutation(int[] keys, int[] before, int[] after, int lo, int hi,
                                        boolean stable, String atom) {
        String where = atom + " n=" + before.length + " [" + lo + "," + hi + ")";
        int[] expected = stableOrder(keys, before, lo, hi);
        if (stable) {
            assertArrayEquals(expected, after, where + " stable order");
            return;
        }
        assertArrayEquals(Arrays.copyOfRange(before, 0, lo), Arrays.copyOfRange(after, 0, lo), where + " prefix");
        assertArrayEquals(Arrays.copyOfRange(before, hi, before.length),
                Arrays.copyOfRange(after, hi, after.length), where + " suffix");
        int[] got = Arrays.copyOfRange(after, lo, hi);
        int[] want = Arrays.copyOfRange(before, lo, hi);
        Arrays.sort(got);
        Arrays.sort(want);
        assertArrayEquals(want, got, where + " permutation");
        assertArrayEquals(keysAlong(keys, expected, lo, hi), keysAlong(keys, after, lo, hi), where + " key order");
    }

    static boolean stable(String algorithm) {
        return SortAlgorithm.valueOf(algorithm).isStable();
    }

    /** Labels whose keys are pre-sorted stably on [lo, mid) and [mid, hi): two adjacent runs. */
    static int[] twoRuns(int[] keys, int lo, int mid, int hi) {
        int[] a = stableOrder(keys, identity(keys.length), lo, mid);
        return stableOrder(keys, a, mid, hi);
    }

    /** Recording monitor for the context protocol. */
    static final class RecordingMonitor implements ProgressMonitor {
        final List<Long> worked = new ArrayList<>();
        int cancelChecks;
        boolean cancelled;

        @Override
        public void worked(long units) {
            worked.add(units);
        }

        @Override
        public boolean isCancelled() {
            return cancelled;
        }

        @Override
        public void checkCancelled() {
            cancelChecks++;
            ProgressMonitor.super.checkCancelled();
        }
    }


    enum LongShape {
        NARROW(true), WIDE_RANDOM(false), EXTREMES(false), FEW(true), EQUAL(true), DESCENDING(false);

        final boolean narrow;

        LongShape(boolean narrow) {
            this.narrow = narrow;
        }
    }

    static long[] longKeys(int n, LongShape shape) {
        Random r = new Random(SEED ^ ((long) n << Integer.SIZE) ^ shape.ordinal());
        long[] extremes = {Long.MIN_VALUE, Long.MAX_VALUE, 0L, -1L, 1L, Long.MIN_VALUE + 1, Long.MAX_VALUE - 1};
        return IntStream.range(0, n).mapToLong(i -> switch (shape) {
            case NARROW -> NARROW_MIN + r.nextInt((int) NARROW_SPAN);
            case WIDE_RANDOM -> r.nextLong();
            case EXTREMES -> extremes[r.nextInt(extremes.length)];
            case FEW -> r.nextInt(FEW_DISTINCT) - 1L;
            case EQUAL -> Long.MIN_VALUE;
            case DESCENDING -> (long) (n - i) << Integer.SIZE;
        }).toArray();
    }

    interface LongVectorCheck {
        void check(long[] keys, int base, int[] order) throws Throwable;
    }

    static void forEachLongVector(boolean narrowOnly, LongVectorCheck check) throws Throwable {
        for (int n : SIZES) {
            for (LongShape s : LongShape.values()) {
                if (narrowOnly && !s.narrow) {
                    continue;
                }
                for (int base : BASES) {
                    check.check(longKeys(n, s), base, IntStream.range(0, n).map(i -> i + base).toArray());
                }
            }
        }
    }

    /** Independent radix digit: the sign-biased key as an unsigned BigInteger, shifted and masked. */
    static int biasedDigit(long key, int shift) {
        java.math.BigInteger biased = java.math.BigInteger.valueOf(key).subtract(
                java.math.BigInteger.valueOf(Long.MIN_VALUE));
        return biased.shiftRight(shift).intValue() & DIGIT_MASK;
    }

    static void assertLongSorted(long[] keys, int base, int[] before, int[] after, int from, int to,
                                 boolean stable, String where) {
        Integer[] boxed = IntStream.of(before).boxed().toArray(Integer[]::new);
        Arrays.sort(boxed, from, to, Comparator.comparingLong(i -> keys[i - base]));
        int[] expected = Stream.of(boxed).mapToInt(Integer::intValue).toArray();
        if (stable) {
            assertArrayEquals(expected, after, where + " stable order");
            return;
        }
        int[] got = after.clone();
        int[] want = before.clone();
        Arrays.sort(got);
        Arrays.sort(want);
        assertArrayEquals(want, got, where + " permutation");
        assertArrayEquals(IntStream.of(expected).mapToLong(i -> keys[i - base]).toArray(),
                IntStream.of(after).mapToLong(i -> keys[i - base]).toArray(), where + " key order");
    }

    /** Full-privilege access to one owner type through MethodHandles.privateLookupIn. */
    static final class Access {
        final Class<?> type;
        private final MethodHandles.Lookup lookup;

        Access(String binaryName) {
            try {
                type = Class.forName(binaryName);
                lookup = MethodHandles.privateLookupIn(type, MethodHandles.lookup());
            } catch (ReflectiveOperationException e) {
                throw new AssertionError("cannot open " + binaryName, e);
            }
        }

        /** The unique declared, non-synthetic method {@code atom} with {@code arity} parameters. */
        MethodHandle method(String atom, int arity) {
            Method found = null;
            for (Method m : type.getDeclaredMethods()) {
                if (m.getName().equals(atom) && m.getParameterCount() == arity && !m.isSynthetic()) {
                    assertEquals(null, found, "ambiguous atom " + atom + "/" + arity);
                    found = m;
                }
            }
            assertTrue(found != null, "missing atom " + atom + "/" + arity);
            try {
                return lookup.unreflect(found);
            } catch (IllegalAccessException e) {
                throw new AssertionError(atom, e);
            }
        }

        /** The unique declared method {@code atom} whose parameter types print as {@code signature}. */
        MethodHandle method(String atom, String signature) {
            for (Method m : type.getDeclaredMethods()) {
                if (m.getName().equals(atom) && !m.isSynthetic() && signature(m.getParameterTypes()).equals(signature)) {
                    try {
                        return lookup.unreflect(m);
                    } catch (IllegalAccessException e) {
                        throw new AssertionError(atom, e);
                    }
                }
            }
            throw new AssertionError("missing atom " + atom + "(" + signature + ")");
        }

        /** The declared constructor with {@code arity} parameters; {@code atom} must be the simple type name. */
        MethodHandle constructor(String atom, int arity) {
            assertEquals(type.getSimpleName(), atom, "constructor atoms carry the type name");
            for (Constructor<?> c : type.getDeclaredConstructors()) {
                if (c.getParameterCount() == arity && !c.isSynthetic()) {
                    try {
                        return lookup.unreflectConstructor(c);
                    } catch (IllegalAccessException e) {
                        throw new AssertionError(atom, e);
                    }
                }
            }
            throw new AssertionError("missing constructor " + atom + "/" + arity);
        }

        /** The declared constructors, for the private non-instantiable utility pattern. */
        Constructor<?>[] constructors() {
            return type.getDeclaredConstructors();
        }

        /** A VarHandle over a declared instance or static field. */
        VarHandle field(String name) {
            try {
                java.lang.reflect.Field f = type.getDeclaredField(name);
                return Modifier.isStatic(f.getModifiers())
                        ? lookup.findStaticVarHandle(type, name, f.getType())
                        : lookup.findVarHandle(type, name, f.getType());
            } catch (ReflectiveOperationException e) {
                throw new AssertionError(name, e);
            }
        }

        /** The value of a declared static constant, read once through its VarHandle. */
        Object constant(String name) {
            return field(name).get();
        }

        private static String signature(Class<?>[] types) {
            StringBuilder b = new StringBuilder();
            for (Class<?> t : types) {
                if (b.length() > 0) {
                    b.append(',');
                }
                b.append(t.getSimpleName());
            }
            return b.toString();
        }
    }
