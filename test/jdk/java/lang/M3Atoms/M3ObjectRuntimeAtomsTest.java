    /** Listener recording deliveries from the framework dispatch thread. */
    static final class Recorder implements ObjectChangeListener {
        final BlockingQueue<ObjectEvent> events = new LinkedBlockingQueue<>();
        final List<Thread> threads = new ArrayList<>();

        @Override
        public void onChange(ObjectEvent event) {
            synchronized (threads) {
                threads.add(Thread.currentThread());
            }
            events.add(event);
        }

        ObjectEvent next() throws InterruptedException {
            ObjectEvent e = events.poll(EVENT_TIMEOUT_SECONDS, TimeUnit.SECONDS);
            assertTrue(e != null, "an event is delivered");
            return e;
        }

        void quiet() throws InterruptedException {
            assertEquals(null, events.poll(QUIET_MILLIS, TimeUnit.MILLISECONDS), "no event is delivered");
        }
    }

