    /** copyFlat(src, srcCoder, from, to, dst, out, dstCoder) copies or inflates [from, to) and returns the new end. */
    @Test
    void copyFlat() throws Throwable {
        MethodHandle atom = new Access("java.lang.M3StringBuilderLane").method("copyFlat", 7);
        String latin = "flat-" + (char) E_ACUTE + "-chunk";
        byte[][] cases = {{LATIN1, LATIN1}, {UTF16, UTF16}, {LATIN1, UTF16}};
        for (byte[] coders : cases) {
            byte[] src = encode(latin, coders[0]);
            byte[] dst = encode("_".repeat(latin.length() + 1), coders[1]);
            int end = (int) atom.invoke(src, coders[0], 2, latin.length() - 1, dst, 1, coders[1]);
            assertEquals(1 + latin.length() - 1 - 2, end, "copyFlat returns out + length");
            String copied = latin.substring(2, latin.length() - 1);
            String expected = new StringBuilder("_".repeat(latin.length() + 1))
                    .replace(1, 1 + copied.length(), copied).toString();
            assertEquals(expected, decode(dst, 0, latin.length() + 1, coders[1]), "copyFlat " + Arrays.toString(coders));
        }
    }
