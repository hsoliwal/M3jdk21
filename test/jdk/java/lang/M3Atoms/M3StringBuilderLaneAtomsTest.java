    /** A pool-interned M3String holding {@code s}. */
    static Object m3(String s) throws Throwable {
        return INTERN_CHARS.invoke(s.toCharArray(), 0, s.length());
    }

    /** A tuple-backed M3String: the pool concatenation of two interned halves. */
    static Object m3Tuple(String left, String right) throws Throwable {
        return CONCAT.invoke(m3(left), m3(right));
    }

    /** The UTF-16 text of an M3String, read through java.lang.CharSequence only. */
    static String text(Object m3) {
        return new StringBuilder((CharSequence) m3).toString();
    }

    /** Deterministic corpus: Latin-1, BMP, paired and unpaired surrogates in every adjacency. */
    static List<String> corpus() {
        List<String> out = new ArrayList<>(List.of("a", PAIR, HIGH, LOW, LOW + HIGH, HIGH + HIGH + LOW,
                PAIR + PAIR, "ab" + PAIR + "c" + LOW + PAIR + HIGH, HIGH + LOW + LOW + HIGH));
        Random r = new Random(SEED);
        for (int n : CORPUS_LENGTHS) {
            StringBuilder b = new StringBuilder();
            while (b.length() < n) {
                b.append(ALPHABET[r.nextInt(ALPHABET.length)]);
            }
            out.add(b.toString());
        }
        return out;
    }

    /** The class or "none" of the first throwable raised by {@code action}, else its value. */
    static Object outcome(Supplier<?> action) {
        try {
            return action.get();
        } catch (RuntimeException e) {
            return e.getClass().getName();
        }
    }

    static Object invokeOutcome(MethodHandle h, Object... args) {
        try {
            return h.invokeWithArguments(args);
        } catch (RuntimeException e) {
            return e.getClass().getName();
        } catch (Throwable e) {
            throw new AssertionError(e);
        }
    }

    /** Positions q of low surrogates immediately preceded by a high surrogate. */
    static int[] pairedLows(String s) {
        return IntStream.range(1, s.length())
                .filter(q -> Character.isHighSurrogate(s.charAt(q - 1)) && Character.isLowSurrogate(s.charAt(q)))
                .toArray();
    }

    static Charset utf16Native() {
        return ByteOrder.nativeOrder() == ByteOrder.BIG_ENDIAN ? StandardCharsets.UTF_16BE : StandardCharsets.UTF_16LE;
    }

    /** Builder-shaped flat bytes: one byte per char for LATIN1, native-order UTF-16 otherwise. */
    static byte[] encode(String s, byte coder) {
        return s.getBytes(coder == LATIN1 ? StandardCharsets.ISO_8859_1 : utf16Native());
    }

    static String decode(byte[] bytes, int fromChar, int chars, byte coder) {
        int unit = coder == LATIN1 ? 1 : 2;
        return new String(bytes, fromChar * unit, chars * unit, coder == LATIN1 ? StandardCharsets.ISO_8859_1 : utf16Native());
    }

    private static final MethodHandle TUPLE = new Access("java.lang.M3StringTuple").constructor("M3StringTuple", 4);
    private static final MethodHandle WHOLE = M3_STRING.method("whole", 1);
    private static long nextTupleId = SEED;

    /** A hand-built tuple over two existing M3Strings: no pool canonicalization or flattening. */
    static Object tupleOf(Object left, Object right) throws Throwable {
        long id = nextTupleId++;
        return WHOLE.invoke(TUPLE.invoke(left, right, id, id));
    }
    /**
     * Deterministic builder lane script: flat appends and lifted pieces in the same logical order as a
     * java.lang.StringBuilder reference. Pieces are ranges of long Strings; one piece is empty.
     */
    static final class LaneScript {
        final Access lane = new Access("java.lang.M3StringBuilderLane");
        final Object instance;
        final StringBuilder flat = new StringBuilder();
        final StringBuilder logical = new StringBuilder();
        final byte flatCoder;
        int pieces;

        LaneScript(boolean wideFlat, boolean widePiece) throws Throwable {
            instance = lane.constructor("M3StringBuilderLane", 1).invoke(PIECE_UNITS);
            flatCoder = wideFlat ? UTF16 : LATIN1;
            String latin = "latin-".repeat(PIECE_UNITS / QUARTER);
            String wide = (String.valueOf((char) CJK) + "x").repeat(PIECE_UNITS);
            flat("ab" + (wideFlat ? String.valueOf((char) CJK) : "c"));
            piece(latin, QUARTER, PIECE_UNITS);
            flat("");
            piece(widePiece ? wide : latin, 1, PIECE_UNITS);
            flat("mid" + (char) E_ACUTE);
            piece(latin, 0, 0);
            piece(latin, PIECE_UNITS / 2, PIECE_UNITS / 2);
            flat("tail");
            piece(latin, 0, PIECE_UNITS);
            piece(latin, 1, PIECE_UNITS);
        }

        void flat(String s) {
            flat.append(s);
            logical.append(s);
        }

        void piece(String s, int start, int length) throws Throwable {
            lane.method("push", 5).invoke(instance, s, start, length, flat.length(), flatCoder);
            logical.append(s, start, start + length);
            pieces++;
        }

        byte[] flatBytes() {
            return encode(flat.toString(), flatCoder);
        }

        byte logicalCoder() throws Throwable {
            return (byte) lane.method("logicalCoder", 1).invoke(instance, flatCoder);
        }
    }

    /** Full-privilege access to one owner type through MethodHandles.privateLookupIn. */
    static final class Access {
        final Class<?> type;
        private final MethodHandles.Lookup lookup;

        Access(String binaryName) {
            try {
                type = Class.forName(binaryName);
                lookup = MethodHandles.privateLookupIn(type, MethodHandles.lookup());
            } catch (ReflectiveOperationException e) {
                throw new AssertionError("cannot open " + binaryName, e);
            }
        }

        /** The unique declared, non-synthetic method {@code atom} with {@code arity} parameters. */
        MethodHandle method(String atom, int arity) {
            Method found = null;
            for (Method m : type.getDeclaredMethods()) {
                if (m.getName().equals(atom) && m.getParameterCount() == arity && !m.isSynthetic()) {
                    assertEquals(null, found, "ambiguous atom " + atom + "/" + arity);
                    found = m;
                }
            }
            assertTrue(found != null, "missing atom " + atom + "/" + arity);
            try {
                return lookup.unreflect(found);
            } catch (IllegalAccessException e) {
                throw new AssertionError(atom, e);
            }
        }

        /** The unique declared method {@code atom} whose parameter types print as {@code signature}. */
        MethodHandle method(String atom, String signature) {
            for (Method m : type.getDeclaredMethods()) {
                if (m.getName().equals(atom) && !m.isSynthetic() && signature(m.getParameterTypes()).equals(signature)) {
                    try {
                        return lookup.unreflect(m);
                    } catch (IllegalAccessException e) {
                        throw new AssertionError(atom, e);
                    }
                }
            }
            throw new AssertionError("missing atom " + atom + "(" + signature + ")");
        }

        /** The declared constructor with {@code arity} parameters; {@code atom} must be the simple type name. */
        MethodHandle constructor(String atom, int arity) {
            assertEquals(type.getSimpleName(), atom, "constructor atoms carry the type name");
            for (Constructor<?> c : type.getDeclaredConstructors()) {
                if (c.getParameterCount() == arity && !c.isSynthetic()) {
                    try {
                        return lookup.unreflectConstructor(c);
                    } catch (IllegalAccessException e) {
                        throw new AssertionError(atom, e);
                    }
                }
            }
            throw new AssertionError("missing constructor " + atom + "/" + arity);
        }

        /** The declared constructors, for the private non-instantiable utility pattern. */
        Constructor<?>[] constructors() {
            return type.getDeclaredConstructors();
        }

        /** A VarHandle over a declared instance or static field. */
        VarHandle field(String name) {
            try {
                java.lang.reflect.Field f = type.getDeclaredField(name);
                return Modifier.isStatic(f.getModifiers())
                        ? lookup.findStaticVarHandle(type, name, f.getType())
                        : lookup.findVarHandle(type, name, f.getType());
            } catch (ReflectiveOperationException e) {
                throw new AssertionError(name, e);
            }
        }

        /** The value of a declared static constant, read once through its VarHandle. */
        Object constant(String name) {
            return field(name).get();
        }

        private static String signature(Class<?>[] types) {
            StringBuilder b = new StringBuilder();
            for (Class<?> t : types) {
                if (b.length() > 0) {
                    b.append(',');
                }
                b.append(t.getSimpleName());
            }
            return b.toString();
        }
    }
