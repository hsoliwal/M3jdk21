	private static void independentPackingOracle() {
		Random random = new Random(0x5A17C0DEL);
		for (int trial = 0; trial < 40; trial++) {
			int count = 1 + random.nextInt(60), width = 1 + random.nextInt(1000), extent = 1 + random.nextInt(150);
			M3MasonryModel model = new M3MasonryModel();
			model.setLogicalCount(count);
			model.setItemExtent(extent);
			int[] request = new int[count];
			for (int i = 0; i < count; i++) {
				request[i] = switch (i % 6) { case 0 -> 0; case 1 -> -1; case 2 -> Integer.MAX_VALUE; default -> 1 + random.nextInt(600); };
				model.setTileHeight(i, request[i]);
			}
			model.layout(width, 100_000);
			int columns = Math.max(1, Math.min(8, width / extent));
			long[] depth = new long[columns];
			for (int i = 0; i < count; i++) {
				int shortest = 0;
				for (int c = 1; c < columns; c++) { if (depth[c] < depth[shortest]) { shortest = c; } }
				check(model.itemRect(i, 1) == depth[shortest], "independent packing trial " + trial + " item " + i);
				depth[shortest] += request[i] <= 0 ? extent : Math.min((long) request[i], (long) extent * 4);
			}
			check(model.logicalExtent() == Arrays.stream(depth).max().orElse(0), "independent total extent");
		}
	}

