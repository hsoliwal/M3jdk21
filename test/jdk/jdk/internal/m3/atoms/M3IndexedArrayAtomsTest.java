    record Item(int rank, int id) { }

    /** The seven view factories of M3IndexedArray: predicate, comparator and state-mask selection. */
    enum Kind {
        FILTERED(true, false, false), SORTED(false, true, false), FILTERED_SORTED(true, true, false),
        MASKED(false, false, true), MASKED_SORTED(false, true, true), FILTERED_MASKED(true, false, true),
        FILTERED_MASKED_SORTED(true, true, true);

        final boolean filtered;
        final boolean sorted;
        final boolean stateAware;

        Kind(boolean filtered, boolean sorted, boolean stateAware) {
            this.filtered = filtered;
            this.sorted = sorted;
            this.stateAware = stateAware;
        }
    }

    /** A backing store and its java.util.ArrayList model with lease counts: the oracle for every view. */
    static final class Fixture {
        final M3IndexedArray<Item> backing = new M3IndexedArray<>();
        final List<Item> model = new ArrayList<>();
        final List<Long> handles = new ArrayList<>();
        final Map<Long, Integer> leases = new HashMap<>();

        Fixture() {
            for (int i = 0; i < ITEMS; i++) {
                append(new Item(i * RANK_STRIDE % RANKS, i));
            }
            for (int i = 1; i < ITEMS; i += LEASE_PERIOD) {
                lease(i);
            }
            lease(SHARED_ITEM);
        }

        void append(Item item) {
            handles.add(backing.append(item));
            model.add(item);
        }

        void lease(int index) {
            long handle = handles.get(index);
            backing.retain(handle);
            leases.merge(handle, 1, Integer::sum);
        }

        List<Item> view(Kind kind) {
            int live = M3IndexedArray.LIVE;
            int leased = M3IndexedArray.LEASED;
            return switch (kind) {
                case FILTERED -> backing.filtered(KEEP);
                case SORTED -> backing.sorted(BY_RANK);
                case FILTERED_SORTED -> backing.filteredSorted(KEEP, BY_RANK);
                case MASKED -> backing.maskedStates(live, leased);
                case MASKED_SORTED -> backing.maskedSortedStates(live, leased, BY_RANK);
                case FILTERED_MASKED -> backing.filteredMaskedStates(KEEP, live, leased);
                case FILTERED_MASKED_SORTED -> backing.filteredMaskedSortedStates(KEEP, live, leased, BY_RANK);
            };
        }

        /** Logical order, then predicate and unleased-state selection, then a stable sort (List.sort). */
        List<Item> expected(Kind kind) {
            List<Item> out = new ArrayList<>();
            for (int i = 0; i < model.size(); i++) {
                Item item = model.get(i);
                boolean unleased = leases.getOrDefault(handles.get(i), 0) == 0;
                if ((!kind.filtered || KEEP.test(item)) && (!kind.stateAware || unleased)) {
                    out.add(item);
                }
            }
            if (kind.sorted) {
                out.sort(BY_RANK);
            }
            return out;
        }
    }

