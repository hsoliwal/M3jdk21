    /** updateLeaseMask(slot) derives the state bits from the lease count and bumps only the state epoch. */
    @Test
    void updateLeaseMask() throws Throwable {
        MethodHandle atom = OWNER.method("updateLeaseMask", 1);
        Fixture f = new Fixture();
        int slot = (int) (long) f.handles.get(0);
        int[] leases = (int[]) OWNER.field("leaseCounts").get(f.backing);
        int[] expectedStates = {M3IndexedArray.LIVE, M3IndexedArray.LIVE | M3IndexedArray.LEASED,
                M3IndexedArray.LIVE | M3IndexedArray.LEASED | M3IndexedArray.SHARED};
        for (int owners = 0; owners < expectedStates.length; owners++) {
            leases[slot] = owners;
            long version = f.backing.version();
            long epoch = stateVersion(f);
            atom.invoke(f.backing, slot);
            assertEquals(expectedStates[owners], ((int[]) OWNER.field("states").get(f.backing))[slot], "owners=" + owners);
            assertEquals(version, f.backing.version(), "values unchanged");
            assertEquals(epoch + 1, stateVersion(f), "updateLeaseMask bumps the state epoch");
        }
        leases[slot] = 0;
        atom.invoke(f.backing, slot);
    }
