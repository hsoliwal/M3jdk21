    /** The class or "none" of the first throwable raised by {@code action}. */
    static String thrown(Supplier<?> action) {
        try {
            action.get();
            return "none";
        } catch (RuntimeException e) {
            return e.getClass().getName();
        }
    }

    /** Scripted forward-then-backward walk recording only the focused ListIterator method. */
    static List<Object> trace(ListIterator<Item> it, String focus) {
        List<Object> out = new ArrayList<>();
        while (true) {
            observe(it, focus, out);
            if (!it.hasNext()) {
                break;
            }
            Item value = it.next();
            if (focus.equals("next")) {
                out.add(value);
            }
        }
        if (focus.equals("next")) {
            out.add(thrown(it::next));
        }
        while (true) {
            observe(it, focus, out);
            if (!it.hasPrevious()) {
                break;
            }
            Item value = it.previous();
            if (focus.equals("previous")) {
                out.add(value);
            }
        }
        if (focus.equals("previous")) {
            out.add(thrown(it::previous));
        }
        return out;
    }

    private static void observe(ListIterator<Item> it, String focus, List<Object> out) {
        switch (focus) {
            case "hasNext" -> out.add(it.hasNext());
            case "hasPrevious" -> out.add(it.hasPrevious());
            case "nextIndex" -> out.add(it.nextIndex());
            case "previousIndex" -> out.add(it.previousIndex());
            default -> { }
        }
    }

    /** All elements of a spliterator, splitting recursively; split sizes are part of the record. */
    static List<Object> splitTrace(Spliterator<Item> s) {
        List<Object> out = new ArrayList<>();
        Spliterator<Item> prefix = s.trySplit();
        if (prefix != null) {
            out.add("split" + prefix.estimateSize() + "/" + s.estimateSize());
            out.addAll(splitTrace(prefix));
            out.addAll(splitTrace(s));
        } else {
            s.forEachRemaining(out::add);
        }
        return out;
    }

