import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.fail;

import java.io.ByteArrayOutputStream;
import java.io.PrintStream;
import java.lang.reflect.AccessibleObject;
import java.lang.reflect.Field;
import java.lang.reflect.InvocationTargetException;
import java.lang.reflect.Modifier;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Comparator;
import java.util.EnumMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.function.Supplier;
import java.util.regex.Pattern;
import java.util.stream.IntStream;
import java.util.stream.Stream;
import org.junit.jupiter.api.Assumptions;

/**
 * Runner of the generated jdk.m3.graphics atom tests (M3GraphicsAtomsTestNN, generated by
 * m3/tooling/skija-absorb/tools/gen_atom_tests.py). One {@link Atom} per test: every listed member is called on the
 * M3 type and on the oracle type with the same deterministic cases (M3GraphicsAtomsValues), and the outcomes are
 * compared structurally (M3GraphicsAtomsCompare): the result or the thrown type, the result's aliasing of the receiver
 * and arguments, the receiver and arguments after the call, the atom's public static mutable fields, and the console
 * output (digit runs collapsed, so timestamps compare). A call that reaches native code (a LinkageError on either side)
 * fails the test: the generator lists only members it found pure, and natives are BLOCKED_NATIVES in ATOM_TESTS.tsv.
 * The number of cases per member is {@link #cases}; the generator computes the same numbers and the test checks them.
 */
final class M3GraphicsAtoms {
    /** The member kinds the generator emits. */
    enum Kind { CTOR, METHOD, STATIC_METHOD, FIELD, STATIC_FIELD }

    static final int ONCE = 1;
    static final int RECEIVER_ROUNDS = 12;
    static final int ARG_ROUNDS = 24;
    static final int ENUM_ARG_ROUNDS = 4;
    private static final int MAX_REPORTED = 25;
    private static final String ORACLE_MISSING = "oracle jars not configured: -D"
            + M3GraphicsAtomsOracle.ORACLE_PROPERTY + "=<skija-shared-0.143.18.jar><path separator><types-0.2.0.jar>";
    private static final Pattern CONSOLE_NUMBERS = Pattern.compile("[0-9][0-9:.TZ+-]*");
    private static final String ZERO = "0";
    private static final String ROW = "ATOM";
    private static final String TAB = "\t";
    private static final String NEWLINE = "\n";
    private static final String HASH = "#";
    private static final String COLON = ": ";
    private static final String DOT = ".";
    private static final String SEPARATOR = " / ";
    private static final String RESULT = "result";
    private static final String ALIASES = "aliases";
    private static final String RECEIVER = "receiver";
    private static final String ARGS = "args";
    private static final String STATICS = "statics";
    private static final String CONSOLE = "console";
    private static final String HASH_CODE_KEY = ".hashCode()";
    private static final String UNSATISFIED_LINK = UnsatisfiedLinkError.class.getName();
    private static final Pattern LOADER_FRAME = Pattern.compile(".*[.]impl[.](M3)?Library");
    private static final Pattern LOADER_METHOD = Pattern.compile("staticLoad|load|_loadFrom.*|_nAfterLoad");
    private static final String NATIVE = "native code reached (generator classified the member pure): ";
    private static final String MISSING = "member not found: ";
    private static final String CASE_COUNT = "cases run vs generated: ";
    private static final String MISMATCHES = " mismatching cases; first ";
    private static final int FIRST_ARG_BIT = 1;

    private M3GraphicsAtoms() {}

    /** The atom of a short donor name; aborts (JUnit assumption) when the oracle jars are not configured. */
    static Atom atom(String shortName) {
        Assumptions.assumeTrue(M3GraphicsAtomsOracle.present(), ORACLE_MISSING);
        return new Atom(shortName);
    }

    /** Cases of one member: the generator emits the same rule (gen_atom_tests.py cases()). */
    static int cases(Kind kind, int params, int constants) {
        boolean enumAtom = constants > 0;
        return switch (kind) {
            case CTOR -> params == 0 ? ONCE : ARG_ROUNDS;
            case STATIC_METHOD -> params == 0 ? ONCE : enumAtom ? constants * ENUM_ARG_ROUNDS : ARG_ROUNDS;
            case METHOD -> enumAtom ? constants * (params == 0 ? ONCE : ENUM_ARG_ROUNDS)
                    : params == 0 ? RECEIVER_ROUNDS : ARG_ROUNDS;
            case STATIC_FIELD -> ONCE;
            case FIELD -> enumAtom ? constants : RECEIVER_ROUNDS;
        };
    }

    /** The key of a member: it names the member in messages and seeds its random rounds. */
    static String key(String atom, String name, String descriptor) {
        return atom + DOT + name + descriptor;
    }

    /** Case {@code i} of a member as logical values: the receiver (ABSENT for a static member), then the arguments. */
    static List<M3GraphicsAtomsValues.Logical> logicalCase(String atom, Kind kind, String key, List<String> tokens,
            int i) {
        int constants = M3GraphicsAtomsValues.isEnum(atom) ? M3GraphicsAtomsValues.constants(atom) : 0;
        boolean instance = kind == Kind.METHOD || kind == Kind.FIELD;
        int round = instance && constants > 0 ? i / constants : i;
        M3GraphicsAtomsValues.Context ctx = new M3GraphicsAtomsValues.Context(atom, M3GraphicsAtomsValues.seed(key),
                kind == Kind.STATIC_METHOD ? M3GraphicsAtomsValues.names(atom) : List.of());
        Stream<M3GraphicsAtomsValues.Logical> recv = Stream.of(instance ? M3GraphicsAtomsValues.receiver(atom, i)
                : M3GraphicsAtomsValues.ABSENT);
        return Stream.concat(recv, IntStream.range(0, tokens.size())
                .mapToObj(p -> M3GraphicsAtomsValues.arg(tokens.get(p), ctx, round, p))).toList();
    }

    /** A resolved member on both sides. */
    record Call(Kind kind, String key, Map<M3GraphicsAtomsOracle.Side, AccessibleObject> targets) {}

    /** What one side did for one case. */
    record Outcome(Object result, Throwable thrown, Object receiver, Object[] args, int aliases, String console,
            List<Object> statics) {}

    /** The members of one atom, run as they are listed; {@link #verify} reports and fails on any mismatch. */
    static final class Atom {
        private final String atom;
        private final int constants;
        private final Map<M3GraphicsAtomsOracle.Side, Class<?>> types = new EnumMap<>(M3GraphicsAtomsOracle.Side.class);
        private final List<String> mismatches = new ArrayList<>();
        private int cases;
        private int members;
        private int identityHashes;

        Atom(String atom) {
            this.atom = atom;
            Arrays.stream(M3GraphicsAtomsOracle.Side.values())
                    .forEach(s -> types.put(s, M3GraphicsAtomsOracle.atom(atom, s)));
            this.constants = M3GraphicsAtomsValues.isEnum(atom) ? M3GraphicsAtomsValues.constants(atom) : 0;
        }

        /** Runs every case of one member (descriptor: parameter tokens only, short donor names). */
        Atom member(Kind kind, String name, String descriptor) {
            List<String> tokens = M3GraphicsAtomsOracle.params(descriptor);
            String key = key(atom, name, descriptor);
            int n = cases(kind, tokens.size(), constants);
            resolve(kind, name, descriptor, key)
                    .ifPresent(c -> IntStream.range(0, n).forEach(i -> check(c, tokens, i)));
            cases += n;
            members++;
            return this;
        }

        /** Prints the atom row and fails when the case count differs from the generator's or any case mismatched. */
        void verify(int generatedCases) {
            System.out.println(String.join(TAB, ROW, atom, String.valueOf(members), String.valueOf(cases),
                    String.valueOf(mismatches.size()), String.valueOf(M3GraphicsAtomsCompare.normalizedAndReset()),
                    String.valueOf(M3GraphicsAtomsHashes.skippedAndReset() + identityHashes),
                    String.valueOf(M3GraphicsAtomsCompare.environmentAndReset())));
            assertEquals(generatedCases, cases, CASE_COUNT + atom);
            if (!mismatches.isEmpty()) {
                fail(atom + COLON + mismatches.size() + MISMATCHES + MAX_REPORTED + COLON + NEWLINE
                        + String.join(NEWLINE, mismatches.subList(0, Math.min(MAX_REPORTED, mismatches.size()))));
            }
        }

        private Optional<Call> resolve(Kind kind, String name, String descriptor, String key) {
            Map<M3GraphicsAtomsOracle.Side, AccessibleObject> targets = new EnumMap<>(M3GraphicsAtomsOracle.Side.class);
            try {
                for (M3GraphicsAtomsOracle.Side s : M3GraphicsAtomsOracle.Side.values()) {
                    targets.put(s, M3GraphicsAtomsOracle.member(types.get(s), kind, name,
                            M3GraphicsAtomsOracle.types(descriptor, s)));
                }
                return Optional.of(new Call(kind, key, targets));
            } catch (ReflectiveOperationException e) {
                mismatches.add(MISSING + key + COLON + e);
                return Optional.empty();
            }
        }

        private void check(Call c, List<String> tokens, int i) {
            List<M3GraphicsAtomsValues.Logical> l = logicalCase(atom, c.kind(), c.key(), tokens, i);
            List<M3GraphicsAtomsValues.Logical> args = l.subList(1, l.size());
            Outcome m3 = run(M3GraphicsAtomsOracle.Side.M3, c, l.get(0), args);
            Outcome oracle = run(M3GraphicsAtomsOracle.Side.ORACLE, c, l.get(0), args);
            boolean hashed = c.kind() == Kind.METHOD && c.key().endsWith(HASH_CODE_KEY);
            boolean comparable = !hashed || M3GraphicsAtomsHashes.stable(oracle.receiver());
            identityHashes += comparable ? 0 : 1;
            compare(m3, oracle, comparable).ifPresent(d -> mismatches.add(c.key() + HASH + i + COLON + d));
        }

        private Outcome run(M3GraphicsAtomsOracle.Side side, Call c, M3GraphicsAtomsValues.Logical recv,
                List<M3GraphicsAtomsValues.Logical> args) {
            ByteArrayOutputStream buf = new ByteArrayOutputStream();
            PrintStream out = System.out;
            PrintStream err = System.err;
            PrintStream capture = new PrintStream(buf, true, StandardCharsets.UTF_8);
            System.setOut(capture);
            System.setErr(capture);
            try {
                return execute(side, c, recv, args, buf);
            } finally {
                System.setOut(out);
                System.setErr(err);
            }
        }

        private Outcome execute(M3GraphicsAtomsOracle.Side side, Call c, M3GraphicsAtomsValues.Logical recv,
                List<M3GraphicsAtomsValues.Logical> logical, ByteArrayOutputStream buf) {
            Object receiver = null;
            Object[] args = new Object[logical.size()];
            try {
                receiver = M3GraphicsAtomsValues.materialize(recv, side);
                for (int p = 0; p < args.length; p++) {
                    args[p] = M3GraphicsAtomsValues.materialize(logical.get(p), side);
                }
                Object result = M3GraphicsAtomsOracle.call(c.targets().get(side), c.kind(), receiver, args);
                return new Outcome(result, null, receiver, args, aliases(result, receiver, args), console(buf),
                        statics(side));
            } catch (Throwable t) {
                Throwable cause = t instanceof InvocationTargetException ite ? ite.getCause() : t;
                return new Outcome(null, cause, receiver, args, 0, console(buf), statics(side));
            }
        }

        private List<Object> statics(M3GraphicsAtomsOracle.Side side) {
            return Arrays.stream(types.get(side).getFields()).filter(Atom::isMutableStatic)
                    .sorted(Comparator.comparing(Field::getName)).map(Atom::read).toList();
        }

        private static boolean isMutableStatic(Field f) {
            return Modifier.isStatic(f.getModifiers()) && !Modifier.isFinal(f.getModifiers());
        }

        private static Object read(Field f) {
            try {
                return f.get(null);
            } catch (IllegalAccessException e) {
                return e.getClass().getName();
            }
        }

        private static String console(ByteArrayOutputStream buf) {
            return CONSOLE_NUMBERS.matcher(buf.toString(StandardCharsets.UTF_8)).replaceAll(ZERO);
        }

        private static int aliases(Object result, Object receiver, Object[] args) {
            int bits = result != null && result == receiver ? 1 : 0;
            for (int p = 0; p < args.length; p++) {
                bits |= result != null && result == args[p] ? FIRST_ARG_BIT << (p + 1) : 0;
            }
            return bits;
        }

        private static Optional<String> compare(Outcome m, Outcome o, boolean resultComparable) {
            if (reachesNatives(m.thrown()) || reachesNatives(o.thrown())) {
                return Optional.of(NATIVE + M3GraphicsAtomsCompare.show(m.thrown()) + SEPARATOR
                        + M3GraphicsAtomsCompare.show(o.thrown()));
            }
            Object mResult = resultComparable ? m.result() : null;
            Object oResult = resultComparable ? o.result() : null;
            return Stream.<Supplier<Optional<String>>>of(
                    () -> M3GraphicsAtomsCompare.outcomes(RESULT, new M3GraphicsAtomsCompare.Result(mResult,
                            m.thrown()), new M3GraphicsAtomsCompare.Result(oResult, o.thrown())),
                    () -> M3GraphicsAtomsCompare.diff(ALIASES, m.aliases(), o.aliases()),
                    () -> M3GraphicsAtomsCompare.diff(RECEIVER, m.receiver(), o.receiver()),
                    () -> M3GraphicsAtomsCompare.diff(ARGS, m.args(), o.args()),
                    () -> M3GraphicsAtomsCompare.diff(STATICS, m.statics(), o.statics()),
                    () -> M3GraphicsAtomsCompare.diff(CONSOLE, m.console(), o.console()))
                    .map(Supplier::get).flatMap(Optional::stream).findFirst();
        }

        /**
         * True when a throwable comes from native code or from the native library loader: an UnsatisfiedLinkError, or
         * a frame of a loading method of impl.Library / impl.M3Library (staticLoad, load, _loadFrom*, _nAfterLoad)
         * anywhere in its cause chain. A JDK 21 "Could not initialize class" error carries the first failure as its
         * cause, so a later use is caught too. Other linkage errors (a missing JDK class) are ordinary outcomes and
         * compare by type.
         */
        private static boolean reachesNatives(Throwable t) {
            return Stream.iterate(t, x -> x != null, Throwable::getCause)
                    .anyMatch(x -> x instanceof UnsatisfiedLinkError
                            || String.valueOf(x.getMessage()).contains(UNSATISFIED_LINK)
                            || Arrays.stream(x.getStackTrace()).anyMatch(Atom::isLoaderFrame));
        }

        private static boolean isLoaderFrame(StackTraceElement f) {
            return LOADER_FRAME.matcher(f.getClassName()).matches()
                    && LOADER_METHOD.matcher(f.getMethodName()).matches();
        }
    }
}
