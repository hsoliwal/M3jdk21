import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertSame;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.junit.jupiter.api.Assertions.fail;

import java.io.IOException;
import java.lang.reflect.InvocationTargetException;
import java.lang.reflect.Method;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.Optional;

/**
 * Plain contract checks of jdk.m3.graphics atoms without a donor class (M3GraphicsAtomsContractTest, generated by
 * m3/tooling/skija-absorb/tools/gen_atom_tests.py). SNEAKY_THROW is Lombok's sneakyThrow, which delombok leaves in the
 * donor code and leaf 1 carries as impl.M3SneakyThrow: the method rethrows the very throwable it gets, checked or not,
 * never returns normally, and a null argument ends in a NullPointerException.
 */
final class M3GraphicsAtomsContracts {
    private static final String RETURNED = "returned normally: ";
    private static final String NOT_SAME = "not the same throwable: ";
    private static final String CASE_COUNT = "contract cases run vs generated: ";
    private static final String CHECKED = "checked";
    private static final String IO = "io";
    private static final String UNCHECKED = "unchecked";
    private static final String ERROR = "error";
    private static final String PLAIN = "plain";
    private static final String DESCRIPTOR = "(Ljava/lang/Throwable;)";
    private static final String ARROW = " -> ";
    private static final String NEWLINE = "\n";
    private static final String DOT = ".";

    private M3GraphicsAtomsContracts() {}

    /** Checks the SNEAKY_THROW contract of a public static method (Throwable) of an M3 class. */
    static void sneakyThrow(String m3Class, String name, int generatedCases) {
        Method m = method(m3Class, name);
        List<Throwable> throwables = Arrays.asList(new Exception(CHECKED), new IOException(IO),
                new IllegalStateException(UNCHECKED), new Error(ERROR), new Throwable(PLAIN), null);
        List<String> failures = new ArrayList<>();
        throwables.forEach(t -> check(m, t).ifPresent(failures::add));
        assertEquals(generatedCases, throwables.size(), CASE_COUNT + m3Class + DESCRIPTOR);
        assertTrue(failures.isEmpty(), String.join(NEWLINE, failures));
    }

    private static Optional<String> check(Method m, Throwable t) {
        try {
            return Optional.of(RETURNED + m.invoke(null, t));
        } catch (InvocationTargetException e) {
            Throwable thrown = e.getCause();
            boolean same = t == null ? thrown instanceof NullPointerException : thrown == t;
            return same ? Optional.empty() : Optional.of(NOT_SAME + t + ARROW + thrown);
        } catch (IllegalAccessException e) {
            return Optional.of(e.toString());
        }
    }

    private static Method method(String m3Class, String name) {
        try {
            Method m = Class.forName(m3Class).getMethod(name, Throwable.class);
            assertSame(RuntimeException.class, m.getReturnType(), m3Class + DESCRIPTOR);
            return m;
        } catch (ReflectiveOperationException e) {
            return fail(m3Class + DOT + name + DESCRIPTOR, e);
        }
    }
}
