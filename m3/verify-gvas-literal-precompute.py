"""Java 21/JNI strict-address proof for a compiler-emitted immutable M3 literal image.

Requires a Linux JVM and C11 compiler; uses no Maven, jar dependencies or developer flags.
The binary input is produced by the actual Java compile-time image writer, then admitted by
three distinct JVMs which MUST all see the same native pointer and inode.
"""
from __future__ import annotations

from contextlib import contextmanager
import hashlib
import os
from pathlib import Path
import re
import subprocess
import tempfile
from typing import Iterator

ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / "ports/compiletime/src/main/java/com/m3/compiletime/M3GvasLiteralImageWriter.java"
OWNER = ROOT / "core/src/com/m3/text/M3FixedAddressMapping.java"
INDEX = ROOT / "core/src/com/m3/text/M3GvasLiteralImage.java"
TEST = ROOT / "core/test/com/m3/text/M3GvasLiteralImageContractTest.java"
C_SOURCE = ROOT / "lexicon/native/m3_fixed_address_mapping_jni.c"
BASE = 0x600000000000
JAVA_CLASS = "com.m3.text.M3GvasLiteralImageContractTest"


def run(*command: str, **kwargs: object) -> subprocess.CompletedProcess[str]:
    return subprocess.run(command, check=True, text=True, **kwargs)


def must_contain(text: str, wanted: str) -> None:
    if wanted not in text:
        raise AssertionError(f"missing {wanted!r}: {text}")


def compile_sources(work: Path, jdk: Path) -> Path:
    javac = jdk / "bin/javac"
    java = jdk / "bin/java"
    run(str(javac), "--release", "21", "-Xlint:all", "-Werror", "-h", str(work),
        "-d", str(work), *(str(path) for path in (SOURCE, OWNER, INDEX, TEST)))
    if not (work / "com_m3_text_M3FixedAddressMapping.h").is_file():
        raise AssertionError("JNI header was not generated by javac -h")
    cc = os.environ.get("CC", "cc")
    lib = work / "libm3gvas.so"
    run(cc, "-std=c11", "-Wall", "-Wextra", "-Werror", "-fPIC", "-shared",
        "-I" + str(jdk / "include"), "-I" + str(jdk / "include/linux"),
        str(C_SOURCE), "-o", str(lib))
    if not lib.exists():
        raise AssertionError("missing JNI library")
    if not java.exists():
        raise AssertionError("missing Java runtime")
    return lib


def java_case(jdk: Path, work: Path, mode: str, lib: Path, image: Path, digest: str) -> str:
    process = run(str(jdk / "bin/java"), "-Xcheck:jni", "-ea", "-esa", "-cp", str(work),
                  JAVA_CLASS, mode, str(lib), str(image), digest,
                  capture_output=True)
    return process.stdout


def _proc_identity(identity: Path, *, require_parent: bool = True) -> tuple[int, int | None, tuple[int, ...]]:
    required = {"Pid", "NSpid", "PPid"} if require_parent else {"Pid", "NSpid"}
    fields: dict[str, tuple[int, ...]] = {}
    for line in identity.read_text().splitlines():
        name, separator, value = line.partition(":")
        if separator and name in required:
            words = value.split()
            if (name in fields or not words
                    or any(re.fullmatch(r"[0-9]+", word) is None for word in words)
                    or (name != "NSpid" and len(words) != 1)):
                raise AssertionError(f"invalid {name} in {identity}")
            fields[name] = tuple(int(word) for word in words)
    if set(fields) != required:
        raise AssertionError(f"missing process identity in {identity}")
    pid, namespace_pids = fields["Pid"][0], fields["NSpid"]
    if pid <= 0 or any(value <= 0 for value in namespace_pids) or namespace_pids[0] != pid:
        raise AssertionError(f"inconsistent process identity in {identity}")
    return pid, fields["PPid"][0] if require_parent else None, namespace_pids


@contextmanager
def proc_child_identity(namespace_pid: int, proc_root: Path = Path("/proc")) -> Iterator[int]:
    """Keep an exact procfs association while inspecting this parent's child.

    Popen.pid stays in the caller's namespace for wait/kill. A numeric /proc path
    with that value may name an unrelated host process. Namespace mismatch uses a
    kernel pidfd; its descriptor remains open through the caller's mapping checks.
    The proof retains its unwaited children until after those checks, preventing
    reuse of an exited child's PID during either route.
    """
    if namespace_pid <= 0:
        raise AssertionError(f"invalid child namespace PID: {namespace_pid}")
    parent_link = os.readlink(proc_root / "self")
    if re.fullmatch(r"[1-9][0-9]*", parent_link) is None:
        raise AssertionError(f"invalid procfs self link: {parent_link!r}")
    parent_proc_pid = int(parent_link)
    parent_pid, _, parent_namespaces = _proc_identity(proc_root / "self/status")
    if parent_pid != parent_proc_pid or parent_namespaces[-1] != os.getpid():
        raise AssertionError("procfs self identity does not match this parent")
    namespace_index = len(parent_namespaces) - 1
    descriptor: int | None = None
    descriptor_namespaces: tuple[int, ...] | None = None
    try:
        if parent_pid == os.getpid() and len(parent_namespaces) == 1:
            proc_pid = namespace_pid
        else:
            descriptor = os.pidfd_open(namespace_pid, 0)
            proc_pid, _, descriptor_namespaces = _proc_identity(
                proc_root / f"self/fdinfo/{descriptor}", require_parent=False)
            if (len(descriptor_namespaces) <= namespace_index
                    or descriptor_namespaces[namespace_index] != namespace_pid):
                raise AssertionError("pidfd identity does not match the child namespace PID")
        pid, parent, namespaces = _proc_identity(proc_root / f"{proc_pid}/status")
        if (pid != proc_pid or parent != parent_proc_pid
                or len(namespaces) <= namespace_index or namespaces[namespace_index] != namespace_pid
                or (descriptor_namespaces is not None and namespaces != descriptor_namespaces)):
            raise AssertionError(f"invalid parent-owned child relationship: {proc_pid}")
        yield proc_pid
    finally:
        if descriptor is not None:
            os.close(descriptor)


def proof(jdk: Path, work: Path, lib: Path, image: Path, digest: str) -> None:
    for mode, token in (("collision", "M3_GVAS_LITERAL_COLLISION_REFUSED"),
                        ("digest", "M3_GVAS_LITERAL_DIGEST_REFUSED")):
        must_contain(java_case(jdk, work, mode, lib, image, digest), token)

    tampered = work / "literal-tampered.m3gvas"
    binary = bytearray(image.read_bytes())
    binary[64 + 20] ^= 0x40   # invalid UTF16 facts for the first canonical row
    tampered.write_bytes(binary)
    must_contain(java_case(jdk, work, "corrupt", lib, tampered,
                           hashlib.sha256(binary).hexdigest()), "M3_GVAS_LITERAL_CORRUPTION_REFUSED")

    processes: list[subprocess.Popen[str]] = []
    results: list[tuple[int, int]] = []
    checks: list[int] = []
    try:
        for mode in ("-Xint", "-Xbatch", "-XX:-CompactStrings"):
            cmd = [str(jdk / "bin/java"), mode, "-Xcheck:jni", "-ea", "-esa",
                   "-cp", str(work), JAVA_CLASS, "child", str(lib), str(image), digest]
            p = subprocess.Popen(cmd, stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                                 stderr=subprocess.PIPE, text=True)
            processes.append(p)
            assert p.stdout is not None
            line = p.stdout.readline().strip()
            m = re.fullmatch(r"M3_GVAS_LITERAL_READY base=0x([0-9a-f]+) hello=0x([0-9a-f]+) checks=(\d+)", line)
            if not m:
                raise AssertionError(f"child refused: {mode} {line} stderr={p.stderr.read() if p.poll() is not None and p.stderr else ''}")
            results.append((int(m.group(1), 16), int(m.group(2), 16)))
            checks.append(int(m.group(3)))
        if not all(base == BASE for base, _ in results):
            raise AssertionError(f"base differs: {results}")
        if len({address for _, address in results}) != 1:
            raise AssertionError(f"canonical hello pointer differs: {results}")
        inode = image.stat().st_ino
        for p in processes:
            with proc_child_identity(p.pid) as proc_pid:
                maps = [line.split() for line in Path(f"/proc/{proc_pid}/maps").read_text().splitlines()
                        if str(image) in line]
                ok = any(int(row[0].split("-")[0], 16) == BASE
                         and row[1] == "r--s" and int(row[2], 16) == 0
                         and int(row[4]) == inode for row in maps)
                if not ok:
                    raise AssertionError(f"same inode/address mapping failed for pid={p.pid} proc_pid={proc_pid}: {maps}")
        for p in processes:
            assert p.stdin is not None
            p.stdin.write("\n")
            p.stdin.flush()
        for p in processes:
            stdout, stderr = p.communicate(timeout=60)
            if p.returncode != 0 or "M3_GVAS_LITERAL_PASS" not in stdout:
                raise AssertionError(f"child failed {p.pid}: {stdout} {stderr}")
        print(f"M3_GVAS_LITERAL_STRICT_PASS processes={len(processes)}"
              f" base=0x{BASE:x} literal=0x{results[0][1]:x}"
              f" inode={inode} checks_per_child={checks[0]} sha256={digest}")
    finally:
        for p in processes:
            if p.poll() is None:
                p.kill()
                p.communicate(timeout=15)


def main() -> None:
    jdk = Path(os.environ.get("M3_JDK", os.environ.get("JAVA_HOME", "/usr/lib/jvm/java-21-openjdk-amd64")))
    if not (jdk / "bin/javac").is_file():
        raise RuntimeError(f"Java 21 JDK missing at {jdk}; set M3_JDK")
    with tempfile.TemporaryDirectory(prefix="m3-gvas-literal-") as temporary:
        work = Path(temporary)
        lib = compile_sources(work, jdk)
        image = work / "literal.m3gvas"
        emitted = run(str(jdk / "bin/java"), "-ea", "-esa", "-cp", str(work),
                      JAVA_CLASS, "emit", str(image), capture_output=True).stdout
        must_contain(emitted, "M3_GVAS_PRECOMPUTE_EMITTED")
        digest = hashlib.sha256(image.read_bytes()).hexdigest()
        proof(jdk, work, lib, image, digest)


if __name__ == "__main__":
    main()
