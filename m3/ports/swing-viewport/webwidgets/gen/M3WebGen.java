import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.util.ArrayList;
import java.util.HexFormat;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/**
 * Deterministic template generator of the M3 web widgets (TmOP, Template-First Generation).
 * <p>
 * usage: {@code java M3WebGen.java <gen-dir> <CONCEPTS.tsv> <nebula-m3web-dir|-> <swing-viewport-dir|-> [FAMILY,...]}
 * <br>
 * Reads {@code spec/MEMBERS.tsv} (concept, family, mode, role, shape, variant, sample, existing classes) and the
 * templates under {@code templates/}; writes core, family and member sources for the Nebula bundle and the
 * M3JDK Swing port. No body is written by hand or by a model: a correction is a template change plus a
 * regeneration, and a second run must change nothing (fixed point; {@code GENERATED.tsv} lists every file
 * with its template and SHA-256).
 * </p>
 */
public final class M3WebGen {
	static final String HEADER = """
			/*******************************************************************************
			 * Copyright (c) 2026 Synexia, Hitesh Soliwal (hsoliwal@gmail.com) and others.
			 *
			 * This program and the accompanying materials are made available under the
			 * terms of the Apache License, Version 2.0, or (at your option) the Eclipse
			 * Public License 2.0, which are available at
			 * https://www.apache.org/licenses/LICENSE-2.0 and
			 * https://www.eclipse.org/legal/epl-2.0/
			 *
			 * SPDX-License-Identifier: Apache-2.0 OR EPL-2.0
			 *
			 * Contributors:
			 *     Hitesh Soliwal (Synexia) - initial API and implementation
			 *******************************************************************************/
			// Generated by M3WebGen from %s; edit the template and regenerate.
			""";
	static final String[] CORE = { "M3WebStates", "M3WebTheme", "M3WebPaint", "M3WebDelta", "M3WebApi", "M3WebLanes", "M3WebView", "M3WebModel", "M3WebGlyphs", "M3WebPixelProbe" };
	final Path gen;
	final Map<String, String> generated = new TreeMap<>();
	final Map<String, Map<String, String>> concepts = new LinkedHashMap<>();
	final List<Map<String, String>> members = new ArrayList<>();
	int written;

	M3WebGen(Path gen) {
		this.gen = gen;
	}

	public static void main(String[] args) throws IOException {
		M3WebGen g = new M3WebGen(Path.of(args[0]));
		g.members.addAll(tsv(g.gen.resolve("spec/MEMBERS.tsv")));
		tsv(Path.of(args[1])).forEach(r -> g.concepts.put(r.get("concept"), r));
		List<String> only = args.length > 4 ? List.of(args[4].split(",")) : List.of();
		if (!args[2].equals("-")) {
			g.side(new Side(Path.of(args[2]), true), only);
		}
		if (!args[3].equals("-")) {
			g.side(new Side(Path.of(args[3]), false), only);
		}
		System.out.println("M3WebGen files=" + g.generated.size() + " written=" + g.written);
	}

	/** Output layout of one toolkit side. */
	record Side(Path root, boolean nebula) {
		String pkg() { return nebula ? "org.eclipse.nebula.widgets.m3web.model" : "com.m3.swing.web.model"; }
		String wpkg() { return nebula ? "org.eclipse.nebula.widgets.m3web" : "com.m3.swing.web"; }
		Path main(String p) { return root.resolve(nebula ? "org.eclipse.nebula.widgets.m3web/src" : "src/main/java").resolve(p.replace('.', '/')); }
		Path test(String p) { return root.resolve(nebula ? "org.eclipse.nebula.widgets.m3web.test/src" : "src/test/java").resolve(p.replace('.', '/')); }
		Path example(String p) { return root.resolve(nebula ? "org.eclipse.nebula.widgets.m3web.snippets/src" : "examples/web").resolve(p.replace('.', '/')); }
		String exists(Map<String, String> m) { return m.get(nebula ? "nebula_existing" : "swing_existing"); }
	}

	void side(Side s, List<String> only) throws IOException {
		Map<String, String> base = Map.of("@PKG@", s.pkg(), "@WPKG@", s.wpkg());
		for (String c : CORE) {
			emit("core/" + c + ".java.tmpl", s.main(s.pkg()).resolve(c + ".java"), base);
		}
		emit("core/M3WebChecks.java.tmpl", s.test(s.pkg()).resolve("M3WebChecks.java"), base);
		emit((s.nebula() ? "nebula/" : "swing/") + "M3WebViewportCore.java.tmpl", s.main(s.pkg()).resolve("M3WebViewportCore.java"), base);
		String tk = s.nebula() ? "nebula/" : "swing/";
		for (String c : s.nebula() ? new String[] { "M3WebCanvas", "M3WebCanvasCache" } : new String[] { "M3WebComponent" }) {
			emit(tk + c + ".java.tmpl", s.main(s.wpkg()).resolve(c + ".java"), base);
		}
		if (!s.nebula()) {
			emit("swing/M3WebComponentChecks.java.tmpl", s.test(s.wpkg()).resolve("M3WebComponentChecks.java"), base);
		}
		for (String fam : families()) {
			if (only.isEmpty() || only.contains(fam)) {
				family(s, fam, base);
			}
		}
		if (s.nebula() && only.isEmpty()) {
			probes(s, base);
		}
		manifest(s);
	}

	/** Desktop pixel probe over the first Nebula-generated member of every family. */
	void probes(Side s, Map<String, String> base) throws IOException {
		StringBuilder b = new StringBuilder();
		List<String> seen = new ArrayList<>();
		for (Map<String, String> m : members) {
			if (s.exists(m).isEmpty() && !seen.contains(m.get("family")) && families().contains(m.get("family"))) {
				seen.add(m.get("family"));
				b.append(b.length() == 0 ? "" : ",\n").append("\t\t\tprobe(new M3").append(pascal(m.get("concept"))).append("(shell, SWT.NONE), \"")
						.append(m.get("sample").replace("\\", "\\\\").replace("\"", "\\\"")).append("\")");
			}
		}
		Map<String, String> v = new LinkedHashMap<>(base);
		v.put("@PROBES@", b.toString());
		emit("nebula/PixelProbe.tmpl", s.example(s.wpkg() + ".snippets").resolve("M3WebPixelProbeSnippet.java"), v);
	}

	List<String> families() {
		List<String> out = new ArrayList<>();
		for (Map<String, String> m : members) {
			if (!out.contains(m.get("family")) && Files.exists(gen.resolve("templates/family/" + m.get("family") + ".java.tmpl"))) {
				out.add(m.get("family"));
			}
		}
		return out;
	}

	void family(Side s, String fam, Map<String, String> base) throws IOException {
		String cls = pascal(fam.toLowerCase());
		emit("family/" + fam + ".java.tmpl", s.main(s.pkg()).resolve("M3" + cls + "Model.java"), base);
		emit("family/" + fam + ".api.tmpl", s.main(s.pkg()).resolve("M3" + cls + "Api.java"), base);
		emit("checks/" + fam + ".checks.tmpl", s.test(s.pkg()).resolve("M3" + cls + "Checks.java"), base);
		for (Map<String, String> m : members) {
			if (m.get("family").equals(fam) && s.exists(m).isEmpty()) {
				member(s, m, cls);
			}
		}
	}

	void member(Side s, Map<String, String> m, String famClass) throws IOException {
		String c = pascal(m.get("concept"));
		Map<String, String> v = new LinkedHashMap<>();
		v.put("@PKG@", s.pkg()); v.put("@WPKG@", s.wpkg()); v.put("@C@", c); v.put("@CONCEPT@", m.get("concept"));
		v.put("@FAMILY@", famClass); v.put("@FAM@", m.get("family")); v.put("@PATTERN@", "M3P-" + m.get("family") + "-1");
		v.put("@MODE@", m.get("mode")); v.put("@ROLE@", m.get("role")); v.put("@SHAPE@", m.get("shape"));
		v.put("@VARIANT@", m.get("variant")); v.put("@SAMPLE@", m.get("sample").replace("\\", "\\\\").replace("\"", "\\\""));
		Map<String, String> row = concepts.getOrDefault(m.get("concept"), Map.of());
		String form = html(row.getOrDefault("viewport_form", ""));
		v.put("@FORM@", form.isEmpty() ? "the family pattern (see CONCEPTS.tsv)" : form);
		v.put("@SWINGX@", row.getOrDefault("swingx_pattern", "").isEmpty() ? "none" : row.get("swingx_pattern").replace(";", ", "));
		emit("member/Api.tmpl", s.main(s.pkg()).resolve("M3" + c + "Api.java"), v);
		emit("member/Model.tmpl", s.main(s.pkg()).resolve("M3" + c + "Model.java"), v);
		String tk = s.nebula() ? "nebula/" : "swing/";
		emit(tk + "Widget.tmpl", s.main(s.wpkg()).resolve("M3" + c + ".java"), v);
		emit(tk + "Test.tmpl", s.nebula() ? s.test(s.pkg()).resolve("M3" + c + "Model_Test.java") : s.test(s.wpkg()).resolve("M3" + c + "Test.java"), v);
		emit(tk + (s.nebula() ? "Snippet.tmpl" : "Example.tmpl"), s.example(s.wpkg() + (s.nebula() ? ".snippets" : ".examples"))
				.resolve("M3" + c + (s.nebula() ? "Snippet.java" : "Example.java")), v);
	}

	void emit(String template, Path out, Map<String, String> vars) throws IOException {
		String body = Files.readString(gen.resolve("templates/" + template), StandardCharsets.UTF_8).replace("\r\n", "\n");
		for (Map.Entry<String, String> e : vars.entrySet()) {
			body = body.replace(e.getKey(), e.getValue());
		}
		if (body.contains("@") && body.matches("(?s).*@[A-Z]+@.*")) {
			throw new IllegalStateException("unbound placeholder in " + template + " -> " + out);
		}
		String text = HEADER.formatted("templates/" + template) + body;
		Files.createDirectories(out.getParent());
		if (!Files.exists(out) || !Files.readString(out, StandardCharsets.UTF_8).equals(text)) {
			Files.writeString(out, text, StandardCharsets.UTF_8);
			written++;
		}
		generated.put(out.toString().replace('\\', '/'), template + "\t" + sha256(text));
	}

	void manifest(Side s) throws IOException {
		StringBuilder b = new StringBuilder("path\ttemplate\tsha256\n");
		String root = s.root().toString().replace('\\', '/') + "/";
		generated.forEach((p, t) -> {
			if (p.startsWith(root)) {
				b.append(p.substring(root.length())).append('\t').append(t).append('\n');
			}
		});
		Path m = s.root().resolve(s.nebula() ? "GENERATED.tsv" : "webwidgets/GENERATED.tsv");
		Files.createDirectories(m.getParent());
		Files.writeString(m, b.toString(), StandardCharsets.UTF_8);
	}

	static String pascal(String concept) {
		StringBuilder b = new StringBuilder();
		for (String part : concept.split("-")) {
			b.append(Character.toUpperCase(part.charAt(0))).append(part.substring(1));
		}
		return b.toString();
	}

	static String html(String s) {
		return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("*/", "*&#47;");
	}

	static String sha256(String s) {
		try {
			return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(s.getBytes(StandardCharsets.UTF_8)));
		} catch (java.security.NoSuchAlgorithmException e) {
			throw new IllegalStateException(e);
		}
	}

	static List<Map<String, String>> tsv(Path p) throws IOException {
		List<String> lines = Files.readAllLines(p, StandardCharsets.UTF_8);
		String[] head = lines.get(0).split("\t", -1);
		List<Map<String, String>> out = new ArrayList<>();
		for (String line : lines.subList(1, lines.size())) {
			String[] f = line.split("\t", -1);
			Map<String, String> row = new LinkedHashMap<>();
			for (int i = 0; i < head.length; i++) {
				row.put(head[i], i < f.length ? f[i] : "");
			}
			out.add(row);
		}
		return out;
	}
}
