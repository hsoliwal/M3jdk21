# Gate 3 of the relocation: donor closure against the relocated classes (target/classes and target/test-classes).
# Donor closure: the main-scope FILE rows of RELOCATION_MAP.tsv (a hash-pinned .java.txt postimage compiles as the .java
# it pins), the TYPE rows without a FILE row (owners an earlier recipe relocated, read from the package of the main
# rows), and the donor source of every QUALIFIED type (an OMIT row names its path); javac --release 21 -Xlint:all
# -Werror. A second donor copy has the LITERAL rows applied (the recipe's only token renames besides names).
# (a) M3IndexPrecomputePlannerDump on the renamed donor and on the relocated classes: byte-identical on the JIT
#     (CASES) and under -Xint (XINT_CASES). The CYCLE_PROBE and CYCLIC lines and the TOTAL line are left out of every
#     comparison: recipe planner-cycle-fix-20261107 deliberately departs from the donor on cyclic greedy catalogues
#     (the donor overflows the stack there; the dump counts that in its default, non-strict mode).
# (b) The same dump on the raw donor: identical to the relocated dump once the H:<sha256> root-hash fields are masked
#     (the LITERAL row of the tuple hash domain is the only difference; the dump checks each hash against MessageDigest
#     with the domain each side declares).
# (c) The crate JUnit tests (test-scope FILE rows) on both sides through the JUnit console launcher: identical result
#     trees after the PACKAGE and TYPE mapping.
# Prints DIFFERENTIAL PASS|FAIL with the sha256 digests. Derived from m3/ports/precompute/recipe/consumer-profiles-20261107/
# differential.sh (renamed-donor lineage, masked raw comparison and the crate-test run of m3/arrays/recipe/lint-storage-20261107).
# usage: differential.sh <donor-git-dir> <donor-rev> <scratch-dir> <junit-platform-console-standalone.jar>
#        [CASES=4000] [XINT_CASES=600]   (JAVA_HOME = JDK 21; run after mvn package)
set -euo pipefail
case "$(uname -s)" in MINGW*|MSYS*|CYGWIN*) SEP=';'; winpath() { (cd "$1" && pwd -W); } ;; *) SEP=':'; winpath() { (cd "$1" && pwd); } ;; esac
RECIPE_DIR=$(winpath "$(dirname "$0")")
MODULE=$(winpath "$(dirname "$0")/../..")
DONOR_GIT=$1
REV=$2
CONSOLE=$4
CASES=${5:-4000}
XINT_CASES=${6:-600}
mkdir -p "$3"
SCRATCH=$(winpath "$3")
JAVA_BIN="${JAVA_HOME:?JAVA_HOME must point at a JDK 21}/bin"
MAP="$RECIPE_DIR/RELOCATION_MAP.tsv"
donor_package=$(awk -F'\t' '$1=="PACKAGE" {print $2; exit}' "$MAP")
target_package=$(awk -F'\t' '$1=="PACKAGE" {print $3; exit}' "$MAP")
package_path=${donor_package//.//}
donor_commit=$(git -C "$DONOR_GIT" rev-parse "$REV^{commit}")
main_dir=$(awk -F'\t' '$1=="FILE" && $3 ~ /^src\/main\/java\// && $2 ~ /\.java$/ {print $2; exit}' "$MAP")
main_dir=${main_dir%/*}
rm -rf "$SCRATCH/src-raw" "$SCRATCH/src-renamed" "$SCRATCH/src-test" "$SCRATCH/raw" "$SCRATCH/renamed" "$SCRATCH/test"
mkdir -p "$SCRATCH/src-raw/$package_path" "$SCRATCH/src-test" "$SCRATCH/raw" "$SCRATCH/renamed" "$SCRATCH/test"
fetch() { # fetch <donor path> <destination>
    mkdir -p "$(dirname "$2")"
    git -C "$DONOR_GIT" show "$REV:$1" > "$2"
    echo "DONOR $donor_commit $1 blob=$(git -C "$DONOR_GIT" rev-parse "$REV:$1" | cut -c1-12)"
}
awk -F'\t' '$1=="FILE" && $3 ~ /^src\/main\/java\// {print $2}' "$MAP" | while read -r path; do
    fetch "$path" "$SCRATCH/src-raw/$package_path/$(basename "$path" .txt)"
done
awk -F'\t' 'NR==FNR {if ($1=="FILE") {n=split($2, p, "/"); sub(/\.txt$/, "", p[n]); sub(/\.java$/, "", p[n]); f[p[n]]=1}; next}
    $1=="TYPE" && !($2 in f) {print $2}' "$MAP" "$MAP" | while read -r type; do
    fetch "$main_dir/$type.java" "$SCRATCH/src-raw/$package_path/$type.java"
done
# A QUALIFIED type is an external interface whose own closure spans other donor modules: the donor compile gets a stub
# generated from the rows (the interface with a no-op checkCanceled and every static factory a QUALIFIED row calls),
# the only members the donor closure uses; the stub is never part of the relocated code.
awk -F'\t' '$1=="QUALIFIED" && $2 !~ /\(/ {print $2}' "$MAP" | while read -r fqn; do
    rel="${fqn//.//}.java"
    mkdir -p "$(dirname "$SCRATCH/src-raw/$rel")"
    {
        echo "package ${fqn%.*};"
        echo "/** Donor-side stub generated by differential.sh (differential only). */"
        echo "public interface ${fqn##*.} {"
        echo "    default void checkCanceled() { }"
        awk -F'\t' -v t="$fqn." '$1=="QUALIFIED" && index($2, t) == 1 && $2 ~ /\(\)$/ {m=substr($2, length(t) + 1); sub(/\(\)$/, "", m); print m}' "$MAP" \
            | while read -r factory; do echo "    static ${fqn##*.} $factory() { return new ${fqn##*.}() { }; }"; done
        echo "}"
    } > "$SCRATCH/src-raw/$rel"
    echo "STUB $fqn ($(grep -c '^    ' "$SCRATCH/src-raw/$rel") members)"
done
cp -r "$SCRATCH/src-raw" "$SCRATCH/src-renamed"
literal_sed="$SCRATCH/literal.sed"
awk -F'\t' '$1=="LITERAL" {d=$2; gsub(/[.]/, "\\.", d); print "s#\"" d "\"#\"" $3 "\"#g"}' "$MAP" > "$literal_sed"
find "$SCRATCH/src-renamed" -name '*.java' -exec sed -i -f "$literal_sed" {} +
compile() { # compile <source tree> <classes>
    "$JAVA_BIN/javac" -J-Djava.io.tmpdir="$SCRATCH" --release 21 -encoding UTF-8 -proc:none -Xlint:all -Werror \
        -d "$2" $(find "$1" -name '*.java')
}
compile "$SCRATCH/src-raw" "$SCRATCH/raw"
compile "$SCRATCH/src-renamed" "$SCRATCH/renamed"
domain_donor=$(awk -F'\t' '$1=="LITERAL" && $2 ~ /:$/ {print $2; exit}' "$MAP")
domain_target=$(awk -F'\t' '$1=="LITERAL" && $2 ~ /:$/ {print $3; exit}' "$MAP")
RELOCATED="$MODULE/target/classes$SEP$MODULE/target/test-classes"
DUMP="$target_package.M3IndexPrecomputePlannerDump"
status=PASS
compare() {
    local left right verdict
    left=$(sha256sum "$SCRATCH/$1.txt" | cut -d' ' -f1)
    right=$(sha256sum "$SCRATCH/$2.txt" | cut -d' ' -f1)
    if cmp -s "$SCRATCH/$1.txt" "$SCRATCH/$2.txt"; then verdict=IDENTICAL; else verdict=DIFFERENT; status=FAIL; fi
    echo "$1 vs $2 $verdict sha256=$left/$right bytes=$(wc -c < "$SCRATCH/$1.txt") lines=$(wc -l < "$SCRATCH/$1.txt")"
}
dump() { # dump <name> <class path> <package> <prefix> <domain> <cases> [jvm flag]
    "$JAVA_BIN/java" -Djava.io.tmpdir="$SCRATCH" ${7:-} -Xss1m -cp "$2" "$DUMP" "$3" "$4" "$5" "$6" | tr -d '\r' > "$SCRATCH/$1.full.txt"
    grep -vE '^(CYCLE_PROBE|CYCLIC|TOTAL) ' "$SCRATCH/$1.full.txt" > "$SCRATCH/$1.txt" || true
}
dump renamed-dump "$SCRATCH/renamed$SEP$MODULE/target/test-classes" "$donor_package" "" "$domain_target" "$CASES"
dump relocated-dump "$RELOCATED" "$target_package" M3 "$domain_target" "$CASES"
compare renamed-dump relocated-dump
dump renamed-dump-xint "$SCRATCH/renamed$SEP$MODULE/target/test-classes" "$donor_package" "" "$domain_target" "$XINT_CASES" -Xint
dump relocated-dump-xint "$RELOCATED" "$target_package" M3 "$domain_target" "$XINT_CASES" -Xint
compare renamed-dump-xint relocated-dump-xint
dump raw-dump "$SCRATCH/raw$SEP$MODULE/target/test-classes" "$donor_package" "" "$domain_donor" "$CASES"
sed -E 's/H:[0-9a-f]{64}/H:<masked>/g' "$SCRATCH/raw-dump.txt" | grep -v '^TOTAL' > "$SCRATCH/raw-dump-masked.txt"
sed -E 's/H:[0-9a-f]{64}/H:<masked>/g' "$SCRATCH/relocated-dump.txt" | grep -v '^TOTAL' > "$SCRATCH/relocated-dump-masked.txt"
compare raw-dump-masked relocated-dump-masked
echo "root-hash fields: $(grep -o 'H:[0-9a-f]\{64\}' "$SCRATCH/relocated-dump.txt" | wc -l) per dump; raw vs relocated unmasked lines differing: $(diff "$SCRATCH/raw-dump.txt" "$SCRATCH/relocated-dump.txt" | grep -c '^>' || true)"
tail -n 1 "$SCRATCH/relocated-dump.full.txt"
tail -n 1 "$SCRATCH/relocated-dump-xint.full.txt"
# (c) crate tests on both sides
cp -r "$SCRATCH/src-raw/." "$SCRATCH/src-test/"
tests=()
while IFS=$'\t' read -r kind donor target _note; do
    [ "$kind" = FILE ] || continue
    case "$target" in src/test/java/*) ;; *) continue ;; esac
    fetch "$donor" "$SCRATCH/src-test/$package_path/$(basename "$donor")" > /dev/null
    tests+=("$(basename "$donor" .java)")
done < "$MAP"
"$JAVA_BIN/javac" -J-Djava.io.tmpdir="$SCRATCH" --release 21 -encoding UTF-8 -proc:none -Xlint:all -Werror \
    -cp "$CONSOLE" -d "$SCRATCH/test" $(find "$SCRATCH/src-test" -name '*.java')
normalize="$SCRATCH/junit-normalize.sed"
awk -F'\t' '$1=="PACKAGE" && $2!=$3 {gsub(/\./, "\\.", $2); print "s/" $2 "/" $3 "/g"}' "$MAP" > "$normalize"
awk -F'\t' '$1=="TYPE" && $2!=$3 {print "s/\\b" $2 "\\b/" $3 "/g"}' "$MAP" >> "$normalize"
junit() { # junit <name> <class path> <package> <prefix>
    local selectors=()
    for t in "${tests[@]}"; do selectors+=(--select-class "$3.$4$t"); done
    "$JAVA_BIN/java" -Djava.io.tmpdir="$SCRATCH" -jar "$CONSOLE" execute --disable-banner --disable-ansi-colors \
        --details=tree --details-theme=ascii -cp "$2" "${selectors[@]}" 2>&1 | tr -d '\r' \
        | grep -vE 'Test run finished after|^stty: ' | sed -f "$normalize" > "$SCRATCH/$1.txt" || true
}
junit donor-junit "$SCRATCH/test" "$donor_package" ""
junit relocated-junit "$RELOCATED" "$target_package" M3
compare donor-junit relocated-junit
grep -E 'tests (successful|failed)' "$SCRATCH/relocated-junit.txt" | tr -s ' ' | tr '\n' ' '; echo
grep -q ' 0 tests failed' "$SCRATCH/relocated-junit.txt" || status=FAIL
echo "DIFFERENTIAL $status"
[ "$status" = PASS ]
