import java.io.ByteArrayOutputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.HexFormat;
import java.util.List;

//FLLDCIM: TFG - atom wc.table_generator: Character.isWhitespace(char) to a two-level C table
/**
 * Template-first generator for {@code native/m3textio_whitespace.h}.
 *
 * <p>The predicate is {@link Character#isWhitespace(char)} over every UTF-16 unit
 * 0x0000..0xFFFF, the exact test Unix4j wc applies per unit. The output is a
 * two-level table (256 page indexes, deduplicated 256-bit pages). The header is
 * byte-deterministic: no timestamps, no JDK update version. Run with
 * {@code java M3TextioWhitespaceTableGenerator.java <out.h>}; the verify script
 * regenerates it and requires a byte-identical fixed point.
 */
public final class M3TextioWhitespaceTableGenerator {
    private static final int UNITS = 0x10000;
    private static final int PAGE_UNITS = 256;
    private static final int WORDS_PER_PAGE = PAGE_UNITS / Long.SIZE;

    private M3TextioWhitespaceTableGenerator() { }

    public static void main(String[] args) throws Exception {
        if (args.length != 1) throw new IllegalArgumentException("usage: <out.h>");
        long[] bits = new long[UNITS / Long.SIZE];
        int count = 0;
        for (int unit = 0; unit < UNITS; unit++) {
            if (Character.isWhitespace((char) unit)) {
                bits[unit >>> 6] |= 1L << (unit & 63);
                count++;
            }
        }
        List<long[]> pages = new ArrayList<>();
        pages.add(new long[WORDS_PER_PAGE]);
        int[] stage1 = new int[UNITS / PAGE_UNITS];
        for (int page = 0; page < stage1.length; page++) {
            long[] words = Arrays.copyOfRange(bits, page * WORDS_PER_PAGE, (page + 1) * WORDS_PER_PAGE);
            int index = indexOf(pages, words);
            if (index < 0) { pages.add(words); index = pages.size() - 1; }
            stage1[page] = index;
        }
        if (pages.size() > 255) throw new IllegalStateException("page index exceeds uint8_t");
        Files.writeString(Path.of(args[0]), header(bits, count, stage1, pages), StandardCharsets.US_ASCII);
    }

    private static int indexOf(List<long[]> pages, long[] words) {
        for (int i = 0; i < pages.size(); i++) if (Arrays.equals(pages.get(i), words)) return i;
        return -1;
    }

    private static String sha256(long[] bits) throws Exception {
        ByteArrayOutputStream bytes = new ByteArrayOutputStream(bits.length * Long.BYTES);
        for (long word : bits) for (int shift = 56; shift >= 0; shift -= 8) bytes.write((int) (word >>> shift) & 0xff);
        return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(bytes.toByteArray()));
    }

    private static String header(long[] bits, int count, int[] stage1, List<long[]> pages) throws Exception {
        StringBuilder out = new StringBuilder(8192);
        out.append("/* SPDX-FileCopyrightText: 2026 Hitesh Soliwal and Contributors to the Synexia Project\n")
           .append(" * SPDX-License-Identifier: Apache-2.0\n")
           .append(" *\n")
           .append(" * GENERATED by native/generator/M3TextioWhitespaceTableGenerator.java; do not edit.\n")
           .append(" * Predicate: java.lang.Character.isWhitespace(char) for units 0x0000..0xFFFF.\n")
           .append(" * Generator runtime: Java SE ").append(System.getProperty("java.specification.version")).append('\n')
           .append(" * Whitespace units: ").append(count).append('\n')
           .append(" * Pages: ").append(pages.size()).append('\n')
           .append(" * Table SHA-256 (8192-byte big-endian 65536-bit set): ").append(sha256(bits)).append('\n')
           .append(" */\n")
           .append("#ifndef M3TEXTIO_WHITESPACE_H\n#define M3TEXTIO_WHITESPACE_H\n\n#include <stdint.h>\n\n")
           .append("#define M3TEXTIO_WS_UNITS ").append(count).append('\n')
           .append("#define M3TEXTIO_WS_PAGES ").append(pages.size()).append("\n\n")
           .append("static const uint8_t m3textio_ws_stage1[256] = {\n");
        for (int row = 0; row < stage1.length; row += 16) {
            out.append("   ");
            for (int i = row; i < row + 16; i++) out.append(' ').append(stage1[i]).append(i == stage1.length - 1 ? "" : ",");
            out.append('\n');
        }
        out.append("};\n\nstatic const uint64_t m3textio_ws_stage2[M3TEXTIO_WS_PAGES][4] = {\n");
        for (int p = 0; p < pages.size(); p++) {
            out.append("    { ");
            for (int w = 0; w < WORDS_PER_PAGE; w++) {
                out.append(String.format("UINT64_C(0x%016X)", pages.get(p)[w])).append(w == WORDS_PER_PAGE - 1 ? "" : ", ");
            }
            out.append(" }").append(p == pages.size() - 1 ? "" : ",").append(" /* page ").append(p).append(" */\n");
        }
        out.append("};\n\n")
           .append("static inline int m3textio_is_whitespace(uint16_t unit) {\n")
           .append("    uint64_t word = m3textio_ws_stage2[m3textio_ws_stage1[unit >> 8]][(unit >> 6) & 3u];\n")
           .append("    return (int)((word >> (unit & 63u)) & UINT64_C(1));\n")
           .append("}\n\n#endif /* M3TEXTIO_WHITESPACE_H */\n");
        return out.toString();
    }
}
