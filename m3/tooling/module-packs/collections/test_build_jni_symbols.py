"""Frozen generated-header parsing cohort for the actual candidate build.py owner.

The linked-library export equality remains an actual pack-build gate. These cases
exercise parsing and refusal; they do not substitute for javac -h or nm execution.
"""
import importlib.util
from pathlib import Path
import sys
import tempfile
import unittest

OWNER = None
PREFIX = "Java_com_m3_collections_M3IndexMaskCompactor_"
EXPECTED = {
    PREFIX + "selectNative",
    PREFIX + "rangeAbiNative",
    PREFIX + "selectRangeNative",
    PREFIX + "positionsAbiNative",
    PREFIX + "selectPositionsNative",
    PREFIX + "selectWindowNative",
    PREFIX + "selectLongWindowNative",
}
RETURNS = {
    "rangeAbiNative": "jint",
    "positionsAbiNative": "jint",
    "selectLongWindowNative": "jlongArray",
}


def declaration(name):
    method = name.removeprefix(PREFIX)
    returned = RETURNS.get(method, "jintArray")
    return ("JNIEXPORT " + returned + " JNICALL\n" + name
            + "\n  (JNIEnv *, jclass);\n")


class JniHeaderSymbolsContract(unittest.TestCase):
    def parse(self, source):
        with tempfile.TemporaryDirectory(prefix="m3-jni-header-contract-") as directory:
            header = Path(directory) / "com_m3_collections_M3IndexMaskCompactor.h"
            header.write_text(source, encoding="utf-8")
            return OWNER.jni_header_symbols(header)

    def test_current_seven_symbol_owner(self):
        source = "/* DO NOT EDIT THIS FILE - it is machine generated */\n"
        source += "#include <jni.h>\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n"
        source += "".join(declaration(name) for name in sorted(EXPECTED))
        source += "#ifdef __cplusplus\n}\n#endif\n"
        self.assertEqual(EXPECTED, self.parse(source))

    def test_comments_are_not_declarations(self):
        source = "/* JNIEXPORT jint JNICALL Java_Fake_block(JNIEnv *); */\n"
        source += "// JNIEXPORT jint JNICALL Java_Fake_line(JNIEnv *);\n"
        source += declaration(PREFIX + "selectNative")
        self.assertEqual({PREFIX + "selectNative"}, self.parse(source))

    def test_multiline_spacing_and_overloaded_mangling(self):
        overloaded = PREFIX + "selectNative___3I_3BI"
        source = declaration(PREFIX + "selectNative")
        source += ("JNIEXPORT\njintArray\nJNICALL\t" + overloaded
                   + " \n(JNIEnv *, jclass, jintArray, jbyteArray, jint);\n")
        self.assertEqual({PREFIX + "selectNative", overloaded}, self.parse(source))

    def test_missing_original_symbol_refuses(self):
        with self.assertRaises(ValueError):
            self.parse(declaration(PREFIX + "rangeAbiNative"))

    def test_empty_header_refuses(self):
        with self.assertRaises(ValueError):
            self.parse("/* no native methods */\n#include <jni.h>\n")

    def test_duplicate_declaration_refuses(self):
        source = declaration(PREFIX + "selectNative")
        with self.assertRaises(ValueError):
            self.parse(source + source)

    def test_malformed_declaration_refuses(self):
        source = declaration(PREFIX + "selectNative")
        for malformed in (
                "JNIEXPORT jint Java_Fake_no_call(JNIEnv *);\n",
                "JNIEXPORT JNICALL Java_Fake_no_return(JNIEnv *);\n",
                "JNIEXPORT jint JNICALL malformed(JNIEnv *);\n",
                "JNIEXPORT jint JNICALL Java_Fake_missing_paren;\n"):
            with self.subTest(malformed=malformed):
                with self.assertRaises(ValueError):
                    self.parse(source + malformed)

    def test_future_header_declaration_remains_in_expected_set(self):
        # A generated owner header is the contract; never silently drop new JNI methods.
        extra = PREFIX + "futureAbiNative"
        source = "".join(declaration(name) for name in sorted(EXPECTED | {extra}))
        self.assertEqual(EXPECTED | {extra}, self.parse(source))


def main():
    global OWNER
    if len(sys.argv) != 2:
        raise SystemExit("usage: test_build_jni_symbols.py /exact/candidate/build.py")
    source = Path(sys.argv[1]).resolve(strict=True)
    specification = importlib.util.spec_from_file_location("m3_collections_build_owner", source)
    if specification is None or specification.loader is None:
        raise RuntimeError("cannot load exact build.py owner")
    OWNER = importlib.util.module_from_spec(specification)
    specification.loader.exec_module(OWNER)
    sys.argv[:] = [sys.argv[0]]
    unittest.main(verbosity=2)


if __name__ == "__main__":
    main()
