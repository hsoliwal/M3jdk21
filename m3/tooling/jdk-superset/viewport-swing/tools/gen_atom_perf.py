def klass(t):
    return t + ".class" if "<" not in t else t[:t.index("<")] + ".class"


def factory(m):
    params = "".join(", " + klass(p) for p in m["params"])
    if m["kind"] == "ctor":
        return f"PerfSupport.ctor({m['owner']}.class{params})"
    if m["kind"] == "adapted":
        inner = f"AtomSupport.virtual({m['owner']}, \"{m['name']}\", {klass(m['ret'])}{params})"
        return f"PerfSupport.adapt({inner}, {klass(m['ret'])}, Enumeration.class)"
    fn = "statik" if m["kind"] == "static" else "virtual"
    return f"AtomSupport.{fn}({m['owner']}.class, \"{m['name']}\", {klass(m['ret'])}{params})"


def call(i, r):
    m = r["mh"]
    args = ([r["recv"]] if r["recv"] else []) + r["args"]
    inv = f"MH_{i}.invokeExact({', '.join(args)})"
    ret = m["ret"]
    if ret == "void":
        return f"{inv};\n            sink += k;"
    if ret in PRIMITIVES:
        return f"sink += ({ret}) {inv};"
    if ret == "boolean":
        return f"sink += ((boolean) {inv}) ? 1 : 0;"
    return f"sink += (({ret}) {inv}) == null ? 0 : 1;"


def generate(rows, pkg, template, cls):
    fields, methods, table = [], [], []
    for i, r in enumerate(rows):
        if r["mh"]:
            fields.append(f"    static final MethodHandle MH_{i} = {factory(r['mh'])};")
        body = r["body"].replace("{MH}", f"MH_{i}") if r["body"] else call(i, r)
        pre = f"            {r['pre']}\n" if r["pre"] else ""
        methods.append(f"    static long b{i}(int ops) throws Throwable {{\n        long sink = 0;\n"
                       f"        for (int i = 0; i < ops; i++) {{\n            int k = i & PerfSupport.MASK;\n{pre}"
                       f"            {body}\n        }}\n        return sink;\n    }}\n")
        table.append(f"            new PerfSupport.Bench(\"{r['atom']}\", \"{r['label']}\", \"{r['route']}\", "
                     f"PerfSupport.{r['ops']}, {cls}::b{i}),")
    return (HEADER + template.replace("//@@FIELDS@@", "\n".join(fields)).replace("//@@METHODS@@", "\n".join(methods))
            .replace("//@@TABLE@@", "\n".join(table)))


def main():
    atoms_tsv, templates, test_root, spec_out = sys.argv[1:5]
    with open(atoms_tsv, encoding="utf-8") as f:
        ids = {r["atom_id"] for r in csv.DictReader([l for l in f if not l.startswith("#")], delimiter="\t")}
    rows = spec()
    unknown = [r["atom"] for r in rows if ":" not in r["atom"] and r["atom"] not in ids]
    if unknown:
        raise SystemExit("perf spec names atoms that ATOMS.tsv does not have: " + ", ".join(unknown))
    for pkg, cls in PERF_CLASS.items():
        with open(os.path.join(templates, "perf", pkg, cls + ".java"), encoding="utf-8") as f:
            template = strip_header(f.read())
        mine = [r for r in rows if r["pkg"] == pkg]
        with open(os.path.join(test_root, pkg, cls + ".java"), "w", encoding="utf-8", newline="\n") as w:
            w.write(generate(mine, pkg, template, cls))
        with open(os.path.join(templates, "perf", "PerfSupport.java"), encoding="utf-8") as f:
            support = strip_header(f.read())
        with open(os.path.join(test_root, pkg, "PerfSupport.java"), "w", encoding="utf-8", newline="\n") as w:
            w.write(HEADER + support)
    with open(spec_out, "w", encoding="utf-8", newline="\n") as w:
        w.write("pkg\tatom\tlabel\troute\tops\tmethod_handle\n")
        for r in rows:
            m = r["mh"]
            w.write(f"{r['pkg']}\t{r['atom']}\t{r['label']}\t{r['route']}\t{r['ops']}\t"
                    f"{(m['kind'] + ' ' + m['owner'] + '.' + m['name']) if m else '-'}\n")
    atoms = sum(1 for r in rows if ":" not in r["atom"])
    print(f"perf rows={len(rows)} atoms={atoms} references/composites={len(rows) - atoms} classes={len(PERF_CLASS)}")


main()
