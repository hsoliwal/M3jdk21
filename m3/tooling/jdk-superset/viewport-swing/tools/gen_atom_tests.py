"""gen_atom_tests.py <ATOMS.tsv> <templates_dir> <test_root> <ATOM_SPEC.tsv> [pkg,...] : JUNIT stage generator (CPU).

For every source file of the viewport-swing group it writes <test_root>/<pkg>/<File>AtomsTest.java: a jtreg-compatible
JUnit 5 class with one dynamic test per census atom of that file (display name = the atom name; overloads add their
parameter types), each calling the pattern harness of the file's family with the atom's name. The harnesses are the
pattern templates (templates/<pkg>/*.java, templates/common/*.java), copied next to the tests with the Synexia header.
Gates (generation fails): every atom has exactly one dynamic test; every atom name has a case in its family's harness
dispatch (static check of the template text); no test class lacks atoms. Writes ATOM_SPEC.tsv (atom -> test, probe)."""
import collections
import csv
import os
import re
import sys

GENERATOR = "m3/tooling/jdk-superset/viewport-swing/tools/gen_atom_tests.py"
HEADER = ("/*\n * SPDX-License-Identifier: Apache-2.0 OR EPL-2.0\n"
          " * Copyright (c) 2026 Synexia, Hitesh Soliwal (hsoliwal@gmail.com) and others\n */\n"
          "// GENERATED by " + GENERATOR + " (VIEWPORT_ATOM_PATTERNS v1); change the generator or its templates.\n\n")

PKG = {
    "list": dict(modules="java.desktop/sun.swing.list:open", flags="-Djava.awt.headless=true -Dm3.swing.viewport=true"),
    "table": dict(modules="java.desktop/sun.swing.table:open java.desktop/javax.swing:open",
                  flags="-Djava.awt.headless=true"),
    "tree": dict(modules="java.desktop/sun.swing.tree:open java.base/java.util:open",
                 flags="-Djava.awt.headless=true"),
}

# file -> (harness class, probe format, run flags override)
FAMILY = {
    "M3RowOffsets": ("ListLanes", 'ListLanes.check("{top}", "{name}")', None),
    "M3PrefixRowOffsets": ("ListLanes", 'ListLanes.check("{top}", "{name}")', None),
    "M3ListRows": ("ListLanes", 'ListLanes.check("{top}", "{name}")', None),
    "M3RowPieces": ("PieceScript", 'PieceScript.check("{name}")', None),
    "M3ListMeasure": ("MeasureScript", 'MeasureScript.check("{name}")', None),
    "M3SorterLanes": ("SorterScript", 'SorterScript.check("{key}")', None),
    "M3SparseSizes": ("SizesScript", 'SizesScript.check("{name}")', None),
    "M3ExpandedState": ("TableScript", 'TableScript.check("{name}")',
                        "-Djava.awt.headless=true -Dm3.swing.viewport=true"),
    "M3FixedHeightLayoutCache": ("CacheScript", 'CacheScript.check(CacheScript.Kind.FIXED, "{simple}", "{name}")',
                                 None),
    "M3VariableHeightLayoutCache": ("CacheScript",
                                    'CacheScript.check(CacheScript.Kind.VARIABLE, "{simple}", "{name}")', None),
}
CASE = re.compile(r'case\s+((?:"[^"]+"\s*,?\s*)+)->')


def strip_header(text):
    """A template's own licence header and template note, replaced by the generated file's header."""
    if text.startswith("/*\n * SPDX-License-Identifier"):
        text = text[text.index("*/\n") + len("*/\n"):]
        if text.startswith("// Template of"):
            text = text[text.index("\n") + 1:]
        text = text.lstrip("\n")
    return text


def read_atoms(path):
    with open(path, encoding="utf-8") as f:
        lines = [l for l in f if not l.startswith("#")]
    return list(csv.DictReader(lines, delimiter="\t"))


def cases(template_text):
    found = set()
    for m in CASE.finditer(template_text):
        found.update(re.findall(r'"([^"]+)"', m.group(1)))
    return found


def harness_text(templates, pkg, harness):
    path = os.path.join(templates, pkg, harness + ".java")
    with open(path, encoding="utf-8") as f:
        return f.read()


def display_names(atoms):
    """The atom name; overloads within an owner add their parameter types; a name still shared by two owners of the
    same file (Host.sort and M3SorterLanes.sort) is qualified with the nested owner's simple name."""
    per_owner = collections.Counter((a["owner"], a["name"]) for a in atoms)
    first = {}
    for a in atoms:
        params = "" if a["params"] == "-" else a["params"]
        first[a["atom_id"]] = a["name"] if per_owner[(a["owner"], a["name"])] == 1 else f"{a['name']}({params})"
    per_file = collections.Counter((a["file"], first[a["atom_id"]]) for a in atoms)
    out = {}
    for a in atoms:
        d = first[a["atom_id"]]
        nested = a["owner"] != a["file"]
        out[a["atom_id"]] = f"{a['owner'].split('.')[-1]}.{d}" if per_file[(a["file"], d)] > 1 and nested else d
    return out, first


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as w:
        w.write(text)


def test_class(top, pkg, atoms, names, first, harness, probe_fmt, flags):
    fqn = f"sun.swing.{pkg}.{top}"
    cls = top + "AtomsTest"
    probes = []
    for a in atoms:
        simple = a["owner"].split(".")[-1]
        key = "Host." + first[a["atom_id"]] if a["owner"].endswith(".Host") else a["name"]
        probe = probe_fmt.format(top=top, name=a["name"], simple=simple, key=key)
        probes.append((a, names[a["atom_id"]], probe))
    tests = ",\n".join(f'            dynamicTest("{d}", () -> {p})' for _, d, p in probes)
    atom_ids = ",\n".join(f'        "{a["atom_id"]}"' for a, _, _ in probes)
    owner_ref = f"    /** The owner under test. */\n    static final Class<?> OWNER = {top}.class;\n\n"
    text = (HEADER +
            "/*\n * @test\n"
            f" * @summary Per-atom JUnit tests of {fqn}: one dynamic test per method and constructor atom of the\n"
            f" *          census, written from the atom's contract and checked against a JDK oracle ({harness}).\n"
            f" * @modules {PKG[pkg]['modules']}\n"
            f" * @run junit/othervm {flags} {cls}\n */\n\n"
            "import static org.junit.jupiter.api.Assertions.assertEquals;\n"
            "import static org.junit.jupiter.api.DynamicTest.dynamicTest;\n\n"
            "import java.util.HashSet;\nimport java.util.List;\nimport java.util.stream.Stream;\n\n"
            "import org.junit.jupiter.api.DynamicTest;\nimport org.junit.jupiter.api.Test;\n"
            "import org.junit.jupiter.api.TestFactory;\n\n"
            f"import {fqn};\n\n"
            f"public class {cls} {{\n\n" + owner_ref +
            f"    /** The census atoms of {top} (owner#name(parameters)), one dynamic test each. */\n"
            f"    static final String[] ATOMS = {{\n{atom_ids}\n    }};\n\n"
            "    @TestFactory\n    Stream<DynamicTest> atoms() {\n        return Stream.of(\n"
            f"{tests}\n        );\n    }}\n\n"
            "    @Test\n    void oneTestPerAtom() {\n"
            "        long tests = atoms().map(DynamicTest::getDisplayName).distinct().count();\n"
            '        assertEquals(ATOMS.length, tests, "one dynamic test per census atom");\n'
            '        assertEquals(ATOMS.length, new HashSet<>(List.of(ATOMS)).size(), "atoms are distinct");\n'
            "    }\n}\n")
    return cls, text, probes


def main():
    atoms_tsv, templates, test_root, spec_out = sys.argv[1:5]
    only = set(sys.argv[5].split(",")) if len(sys.argv) > 5 else None
    atoms = [a for a in read_atoms(atoms_tsv) if only is None or a["package"].split(".")[-1] in only]
    names, first = display_names(atoms)
    by_file = collections.OrderedDict()
    for a in atoms:
        by_file.setdefault(a["file"], []).append(a)
    spec, missing, classes = [], [], 0
    for top, group in by_file.items():
        pkg = group[0]["package"].split(".")[-1]
        harness, probe_fmt, flags = FAMILY[top]
        known = cases(harness_text(templates, pkg, harness))
        for a in group:
            if a["owner"].endswith(".Host"):
                key = "Host." + first[a["atom_id"]]
            elif harness == "ListLanes":
                key = top + "#" + a["name"]
            else:
                key = a["name"]
            if key not in known:
                missing.append(f"{a['atom_id']} (case \"{key}\" in {pkg}/{harness}.java)")
        cls, text, probes = test_class(top, pkg, group, names, first, harness, probe_fmt, flags or PKG[pkg]["flags"])
        write(os.path.join(test_root, pkg, cls + ".java"), text)
        classes += 1
        spec.extend((a["atom_id"], a["pattern"], f"{pkg}/{cls}", d, p) for a, d, p in probes)
    if missing:
        raise SystemExit("atoms without a harness case:\n  " + "\n  ".join(missing))
    copied = 0
    for pkg in sorted({a["package"].split(".")[-1] for a in atoms}):
        for src_dir in (os.path.join(templates, "common"), os.path.join(templates, pkg)):
            for name in sorted(os.listdir(src_dir)):
                if name.endswith(".java"):
                    with open(os.path.join(src_dir, name), encoding="utf-8") as f:
                        write(os.path.join(test_root, pkg, name), HEADER + strip_header(f.read()))
                    copied += 1
    with open(spec_out, "w", encoding="utf-8", newline="\n") as w:
        w.write("atom_id\tpattern\ttest\tdisplay\tprobe\n")
        w.writelines("\t".join(r) + "\n" for r in spec)
    if len(spec) != len(atoms) or len({r[0] for r in spec}) != len(atoms):
        raise SystemExit(f"one test per atom violated: {len(spec)} tests for {len(atoms)} atoms")
    print(f"atoms={len(atoms)} test_classes={classes} harness_files={copied} dynamic_tests={len(spec)}")


main()
