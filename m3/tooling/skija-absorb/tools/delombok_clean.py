"""delombok_clean.py <src_dir> : DELOMBOK_CLEAN v1, run after `lombok.jar delombok`. In place, deterministic, fail-closed:

  - drop whole lines `@lombok.Generated` (marker only) and `// Generated by delombok at <timestamp>` (non-deterministic)
  - drop `import lombok...;` lines (unused after delombok) and the `@Tolerate` marker (it only steers generation)
  - `throw lombok.Lombok.sneakyThrow(x);` -> `throw SneakyThrow.sneakyThrow(x);` with the helper written to
    impl/SneakyThrow.java (same semantics: rethrows the Throwable unchecked) and imported where used
Exits non-zero if any `lombok` token remains. Prints the counts per rule."""
import os
import re
import sys
from collections import Counter

GEN = re.compile(r"^[ \t]*@lombok\.Generated[ \t]*\r?\n", re.M)
STAMP = re.compile(r"^[ \t]*// Generated by delombok at [^\n]*\r?\n", re.M)
IMP = re.compile(r"^import lombok\.[\w.*]+;[ \t]*\r?\n", re.M)
TOL = re.compile(r"@Tolerate\b[ \t]*")
SNEAKY = re.compile(r"\blombok\.Lombok\.sneakyThrow\(")
HELPER = """// SPDX-License-Identifier: Apache-2.0 OR EPL-2.0
// Copyright (c) 2026 Synexia, Hitesh Soliwal (hsoliwal@gmail.com) and others
package io.github.humbleui.skija.impl;

/** Rethrows any Throwable without declaring it (the semantics of Lombok's sneakyThrow, which delombok leaves behind). */
public final class SneakyThrow {
    private SneakyThrow() {
    }

    public static RuntimeException sneakyThrow(Throwable t) {
        throw SneakyThrow.<RuntimeException>rethrow(t);
    }

    @SuppressWarnings("unchecked")
    private static <T extends Throwable> T rethrow(Throwable t) throws T {
        throw (T) t;
    }
}
"""


def main():
    root = sys.argv[1]
    counts, left = Counter(), []
    for dirpath, _, files in os.walk(root):
        for f in sorted(files):
            if not f.endswith(".java"):
                continue
            p = os.path.join(dirpath, f)
            s = open(p, encoding="utf-8", newline="").read()
            o = s
            for name, rx, rep in (("generated", GEN, ""), ("stamp", STAMP, ""), ("import", IMP, ""), ("tolerate", TOL, "")):
                s, n = rx.subn(rep, s)
                counts[name] += n
            s, n = SNEAKY.subn("SneakyThrow.sneakyThrow(", s)
            counts["sneaky"] += n
            if n and "package io.github.humbleui.skija.impl;" not in s:
                s = re.sub(r"(^package [\w.]+;[ \t]*\r?\n)", r"\1import io.github.humbleui.skija.impl.SneakyThrow;\n", s, count=1, flags=re.M)
            if s != o:
                open(p, "w", encoding="utf-8", newline="").write(s)
                counts["files"] += 1
            if re.search(r"\blombok\b", s):
                left.append(p)
    if counts["sneaky"]:
        os.makedirs(os.path.join(root, "impl"), exist_ok=True)
        open(os.path.join(root, "impl", "SneakyThrow.java"), "w", encoding="utf-8", newline="\n").write(HELPER)
    print(" ".join(f"{k}={v}" for k, v in sorted(counts.items())))
    if left:
        print("LOMBOK_LEFT", *left[:5], sep="\n")
        sys.exit(1)


main()
