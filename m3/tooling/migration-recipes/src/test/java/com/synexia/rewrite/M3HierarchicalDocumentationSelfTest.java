package com.synexia.rewrite;
import java.util.List;
import java.util.Map;

/** Standalone mechanical model smoke/regression runner; useful before Maven integration. */
public final class M3HierarchicalDocumentationSelfTest {
    private M3HierarchicalDocumentationSelfTest() {}
    public static void main(String[] args) {
        String h = M3HierarchicalDocumentation.sha256("class A {}");
        var pom = new M3HierarchicalDocumentation.Source("pom.xml", M3HierarchicalDocumentation.sha256("<project/>"), 10, "XML", "", List.of());
        var source = new M3HierarchicalDocumentation.Source("feature/src/main/java/p/C.java", h, 10, "JAVA_AST", "p", List.of("class:C", "method:m"));
        var module = new M3HierarchicalDocumentation.Source("feature/pom.xml", pom.sha256(), 10, "XML", "", List.of());
        var docs = M3HierarchicalDocumentation.render(List.of(pom, source, module), "synexia", "com.synexia");
        var reverse = M3HierarchicalDocumentation.render(List.of(source, module, pom), "synexia", "com.synexia");
        assertTrue(docs.equals(reverse), "input order must not affect generated bytes");
        assertTrue(docs.keySet().stream().anyMatch(x -> x.contains("L0/feature/src/main/java/p/C.java.md")), "L0 every file");
        for (int i = 1; i <= 5; i++) {
            final int level = i;
            assertTrue(docs.keySet().stream().anyMatch(x -> x.contains("/L" + level + "/")), "L" + i + " missing");
        }
        assertTrue(docs.get(".m3/generated-docs/L3/feature/MODULE.md").contains("production"), "module fanin");
        assertTrue(docs.get(".m3/generated-docs/L5/REPOSITORY.md").contains("PROJECT.md"), "repo fanin");
        assertTrue(docs.get(".m3/generated-docs/L0/feature/src/main/java/p/C.java.md").contains("UNVERIFIED"), "proof gating");
        assertTrue(docs.values().stream().allMatch(x -> x.startsWith(M3HierarchicalDocumentation.MARKER)), "owned generation marker");
        assertTrue(docs.size() >= 9, "expected all rollups");
        var generated = new M3HierarchicalDocumentation.Source(".m3/generated-docs/L0/f.md",h,10,"TEXT","",List.of());
        assertTrue(M3HierarchicalDocumentation.render(List.of(source, module, pom, generated),"synexia","com.synexia").equals(docs), "generated files cannot recurse");
        boolean collision = false;
        try { M3HierarchicalDocumentation.render(List.of(source, source), "a", "b"); } catch (IllegalArgumentException ex) { collision = true; }
        assertTrue(collision, "duplicate owner must fail closed");
        boolean traversal = false;
        try { new M3HierarchicalDocumentation.Source("../bad",h,0,"TEXT","",List.of()); } catch (IllegalArgumentException ex) { traversal = true; }
        assertTrue(traversal, "path traversal must fail closed");
        System.out.println("PASS M3 hierarchical documentation pure-model regression: " + docs.size() + " documents across 6 levels");
    }
    private static void assertTrue(boolean condition, String problem) { if (!condition) throw new AssertionError(problem); }
}
