"""gen_atom_tests.py <spec_dir> <template_dir> <test_dir> <patterns_tsv> : ATOM-TEST GENERATOR v1 (CPU, template-first).

The recipe for "a JUnit for every atom": one spec row per method/constructor atom names its contract
PATTERN and the arguments of that pattern; the pattern's template turns the row into one test method,
and every owner source file becomes one jtreg-compatible JUnit class <Owner>AtomTest whose
@TestFactory publishes one DynamicTest per atom. Fix a template (and add a RECIPE_MEMORY.tsv row),
never a generated file.

spec_dir      one <Owner>.atoms per owner source file:
                #class <Owner>AtomTest     #summary <text>     #build <Helper ...>     #import <type>
                #runopts </othervm ...>   #helper <<< java >>>  (class-level helper members)
                #template <CLASS_TEMPLATE> #entry <factory> #returns <type>  (default CLASS, dynamicTest, void;
                the perf harness uses PERF_CLASS, M3AtomPerf.named, M3AtomPerf.Batch)
                @atom <Owner[.Nested]>.<atom> <n> <PATTERN> <oracle words...>
                <arg> = <one-line java>   or   <arg> <<<  multi-line java  >>>
template_dir  <PATTERN>.tmpl bodies with ${arg} placeholders, plus CLASS.tmpl.
test_dir      output directory of the generated classes.
patterns_tsv  TEST_PATTERNS.tsv (atom, pattern, test, oracle) written for the whole spec set.
Exit status 1 on a duplicate atom row, an unknown pattern, a missing argument or a template without
an assertion."""
import os
import re
import string
import sys

ASSERTION = re.compile(r"\bassert[A-Z]\w*\(|\bexpect(Message)?\(|\bfail\(|Oracle\.\w+|\bcheck\w*\(")
GENERATED = "// GENERATED by m3/tooling/atom-tests/gen_atom_tests.py from specs/{spec}; edit the spec or template."
INDENT = "        "
OPTIONAL_ARGS = ("setup", "extra")


def load_templates(template_dir):
    templates = {}
    for name in sorted(os.listdir(template_dir)):
        if name.endswith(".tmpl"):
            with open(os.path.join(template_dir, name), encoding="utf-8") as f:
                templates[name[:-len(".tmpl")]] = f.read()
    return templates


HEADER = re.compile(r"^#(\w+)\s*(.*)$")
ATOM = re.compile(r"^@atom\s+(\S+)\.(\w+)\s+(\d+)\s+(\w+)\s*(.*)$")
ARG = re.compile(r"^(\w+)\s*=\s?(.*)$")
BLOCK = re.compile(r"^(\w+)\s*<<<\s*$")


def parse_spec(path):
    header = {"imports": [], "build": [], "helpers": []}
    rows, row, block, buffer = [], None, None, []
    with open(path, encoding="utf-8") as f:
        for number, raw in enumerate(f, 1):
            line = raw.rstrip("\n")
            if block is not None:
                if line.strip() == ">>>":
                    text = "\n".join(buffer)
                    if row is None:
                        header[block].append(text) if block == "helpers" else header.__setitem__(block, text)
                    else:
                        row["args"][block] = text
                    block, buffer = None, []
                else:
                    buffer.append(line)
                continue
            if not line.strip() or line.startswith("//"):
                continue
            m = ATOM.match(line)
            if m:
                owner, atom, n, pattern, oracle = m.groups()
                row = {"owner": owner, "atom": atom, "n": int(n), "pattern": pattern,
                       "oracle": oracle.strip() or "contract", "args": {}}
                rows.append(row)
                continue
            m = HEADER.match(line)
            if m and row is None:
                key, value = m.groups()
                if key == "helper" and value.strip() == "<<<":
                    block = "helpers"
                elif key in ("import", "build"):
                    header["imports" if key == "import" else "build"].extend(value.split())
                else:
                    header[key] = value
                continue
            m = BLOCK.match(line)
            if m and row is not None:
                block = m.group(1)
                continue
            m = ARG.match(line)
            if m and row is not None:
                row["args"][m.group(1)] = m.group(2)
                continue
            raise SystemExit("%s:%d: unparsed spec line: %s" % (path, number, line))
    if block is not None:
        raise SystemExit("%s: unterminated <<< block %s" % (path, block))
    return header, rows


def method_name(row):
    if "method" in row:
        return row["method"]
    owner = row["owner"].split(".")
    nested = "_".join(owner[1:])
    base = row["atom"] if not nested else nested + "_" + row["atom"]
    return base if row.get("n", 1) == 1 else "%s_%d" % (base, row["n"])


def assign_method_names(rows):
    """Names stay the atom name; only names shared by atoms of different owners get the top owner prefix."""
    counts = {}
    for row in rows:
        counts[method_name(row)] = counts.get(method_name(row), 0) + 1
    for row in rows:
        name = method_name(row)
        row["method"] = name if counts[name] == 1 else row["owner"].split(".")[0] + "_" + name


def render_row(row, templates, spec, returns="void"):
    pattern = row["pattern"]
    if pattern not in templates:
        raise SystemExit("unknown pattern %s in %s" % (pattern, spec))
    args = dict(row.get("args", {}))
    args.setdefault("atom", row["atom"])
    args.setdefault("owner", row["owner"])
    for optional in OPTIONAL_ARGS:
        args.setdefault(optional, "")
    try:
        body = string.Template(templates[pattern]).substitute(args)
    except KeyError as missing:
        raise SystemExit("missing argument %s for %s.%s (%s)" % (missing, row["owner"], row["atom"], pattern))
    if not ASSERTION.search(body):
        raise SystemExit("assertion-free body for %s.%s (%s)" % (row["owner"], row["atom"], pattern))
    lines = [INDENT + line if line.strip() else "" for line in body.strip("\n").split("\n")]
    name = method_name(row)
    label = "%s.%s#%d %s" % (row["owner"], row["atom"], row.get("n", 1), pattern)
    method = "    /** %s; oracle: %s. */\n    static %s %s() throws Throwable {\n%s\n    }\n" % (
        label, row.get("oracle", "contract"), returns, name, "\n".join(lines))
    return name, label, method


def render_class(header, rows, templates, spec):
    methods, entries = [], []
    seen = set()
    assign_method_names(rows)
    for row in rows:
        key = (row["owner"], row["atom"], row.get("n", 1))
        if key in seen:
            raise SystemExit("duplicate atom row %s in %s" % (key, spec))
        seen.add(key)
        name, label, method = render_row(row, templates, spec, header.get("returns", "void"))
        methods.append(method)
        entries.append('                %s("%s", %s::%s)' % (header.get("entry", "dynamicTest"), label, header["class"], name))
    imports = "".join("import %s;\n" % i for i in header.get("imports", []))
    helpers = "\n".join(header.get("helpers", []))
    for row in rows:
        declaration = r"(?m)^\s{4}(?:(?:private|static|public|final)\s+)+[\w<>\[\]?, ]+\s%s\s*\(" % method_name(row)
        if re.search(declaration, helpers):
            raise SystemExit("helper method clashes with generated atom method %s in %s" % (method_name(row), spec))
    return string.Template(templates[header.get("template", "CLASS")]).substitute(
        generated=GENERATED.format(spec=spec), summary=header["summary"], cls=header["class"],
        build=" ".join(header.get("build", [])), imports=imports, entries=",\n".join(entries),
        methods="\n".join(methods), helpers=helpers, runopts=header.get("runopts", ""))


def main():
    spec_dir, template_dir, test_dir, patterns_tsv = sys.argv[1:5]
    templates = load_templates(template_dir)
    rows_out = []
    for spec in sorted(os.listdir(spec_dir)):
        if not spec.endswith(".atoms"):
            continue
        header, rows = parse_spec(os.path.join(spec_dir, spec))
        source = render_class(header, rows, templates, spec)
        with open(os.path.join(test_dir, header["class"] + ".java"), "w", encoding="utf-8", newline="\n") as w:
            w.write(source)
        for row in rows:
            rows_out.append((row["owner"] + "." + row["atom"] + "#" + str(row.get("n", 1)), row["pattern"],
                             header["class"] + "." + method_name(row), row.get("oracle", "contract")))
        print("%s atoms=%d" % (header["class"], len(rows)))
    with open(patterns_tsv, "w", encoding="utf-8", newline="\n") as w:
        w.write("atom\tpattern\ttest\toracle\n")
        w.writelines("\t".join(r) + "\n" for r in rows_out)
    print("generated_atoms=%d" % len(rows_out))


main()
