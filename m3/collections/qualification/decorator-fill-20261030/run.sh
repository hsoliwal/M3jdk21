# Pattern DECORATOR_FILL v1.6 driver: regenerate every five-provider decorator scaffold through M3DecoratorFill and
# write the fully classified ones back into their modules (MANUAL atoms keep the scaffold). Then compile them with
# -Xlint:all -Werror and run M3DecoratorDifferential against Apache Commons Collections 4.5.0 for each TARGETS.tsv row,
# plus the probes named in its probe column (sync: M3SyncProbe + M3LockTraceProbe; predicated: M3PredicatedProbe).
# v1.3 stages: generator rule checks (RULE_CHECKS.tsv) and planted-defect negative controls (NEGATIVE_CONTROLS.tsv from
# NEGATIVE_CONTROLS_SPEC.tsv): every control must be CAUGHT by its check.
# v1.4 (JDK standard): every emitted class passes javac -Xdoclint:all/protected and the M3JdkStandard plugin
# (m3/compiler/jdk-standard): API parameter names from the Commons and JDK sources, imports, Javadoc, 100 columns.
# v1.5 (Transformed family): transformer lanes, TRANSFORM_* lane members, TRANSFORMED_FACTORY and LANE_VIEW over a
# plain-constructor factory of the class itself or of a sibling the Commons source imports.
# Ledgers: METHOD_ATOMS.tsv (one row per method atom), DIFFERENTIAL.tsv (one row per target), PROBES.tsv, MISMATCHES.tsv.
# Usage (repository root): bash m3/collections/qualification/decorator-fill-20261030/run.sh <commons-collections4-4.5.0.jar>
#   <unpacked commons-collections4-4.5.0-sources dir> [work dir]
# JAVA_HOME must be a JDK 21. Exit 0 = every target compiled, showed no mismatch, and every negative control was caught.
set -euo pipefail
JAR="$1"; SRC="$2"; WORK="${3:-${TMPDIR:-/tmp}/m3-decorator-fill}"
# Scaffolds are read from this revision (the five-provider scaffold as generated), so reruns are idempotent.
SCAFFOLD_REV="${SCAFFOLD_REV:-bb66a8c16642a4e898dbc5fc7c3af0d5ed572136}"
Q=m3/collections/qualification/decorator-fill-20261030; I=m3/collections/implementations
S=m3/collections/qualification/five-provider-inventory-20261018/SCAFFOLD_SURFACE.tsv
BIN="$JAVA_HOME/bin"; SEP=":"; case "$(uname -s)" in MINGW*|MSYS*|CYGWIN*) SEP=";";; esac
readme() {
	version=v1.6
	probe=$(awk -F'\t' -v m="$3" '$1 == m { print $5; exit }' "$Q/TARGETS.tsv" | tr -d '\r')
	# a LANES class (Predicated and Transformed families) is the one whose header lists its categories
	if grep -q '^ \* Categories:' "$I/$1/src/main/java/${3//.//}.java"; then
		lanes="It holds one reference to the decorated owner plus the policy lanes of the Commons class (\`predicate\` or
\`transformer\` lanes); elements are never copied and no Entry or Node object is stored.

The bodies are generated by \`$Q/M3DecoratorFill.java\` (pattern DECORATOR_FILL $version) from the five-provider scaffold.
Each method atom is classified against the Commons class and emitted from a template; the categories used are listed in
the class header. No provider implementation code is copied; nested helpers are emitted only where no JDK owner fits."
		if [ "$probe" = predicated ]; then
			proof="Proof: \`$Q/M3DecoratorDifferential.java\` (seeded differential, predicate mode) and \`$Q/M3PredicatedProbe.java\`
(view sweep, MapIterator and ListIterator scripts, serialization order) run against the Commons class, with results in
\`$Q/DIFFERENTIAL.tsv\` and \`$Q/PROBES.tsv\`; planted defects are in \`$Q/NEGATIVE_CONTROLS.tsv\`."
		else
			proof="Proof: \`$Q/M3DecoratorDifferential.java\` runs a seeded reflective differential against the Commons class for
each lane policy in \`$Q/TARGETS.tsv\`, with results in \`$Q/DIFFERENTIAL.tsv\`; generator rule checks are in
\`$Q/RULE_CHECKS.tsv\`."
		fi
	else
		lanes="It holds one reference to the decorated owner; elements are never copied and no Entry or Node object is stored.

The bodies are generated by \`$Q/M3DecoratorFill.java\` from the five-provider scaffold. Each method atom is classified
against the Commons class as THROW, DELEGATE, EQUALS, WRAP, DEFAULT or FACTORY and emitted from a template; no provider
implementation code is copied. Views use the JDK unmodifiable owners (\`java.util.Collections\`) or this class's own factory."
		proof="Proof: \`$Q/M3DecoratorDifferential.java\` runs a seeded reflective differential against the Commons class, with results in
\`$Q/DIFFERENTIAL.tsv\`. Atom rows are in \`$Q/METHOD_ATOMS.tsv\`."
	fi
	cat > "$I/$1/README.md" <<EOF
<!-- SPDX-License-Identifier: Apache-2.0 -->
<!-- GENERATED by $Q/run.sh (pattern DECORATOR_FILL $version); regenerate, do not hand-edit. -->
# OWNED: ${3##*.}

\`$3\` is an owned decorator with the public contract of \`$2\` (Apache Commons Collections 4.5.0, Apache-2.0).
$lanes

$proof
EOF
}
rm -rf "$WORK" && mkdir -p "$WORK/gen" "$WORK/out" "$WORK/cls" "$WORK/hcls" "$WORK/nc"
echo "M3_DECORATOR_FILL stage=generator"
# The generator is four atoms: the CLI and classifier, its helper templates, the JDK_STANDARD pass and the rule checks.
ATOMS=("$Q/M3DecoratorTemplates.java" "$Q/M3DecoratorJdkStandard.java" "$Q/M3DecoratorRuleCheck.java")
"$BIN/javac" -proc:none -cp "$JAR" -d "$WORK/gen" "$Q/M3DecoratorFill.java" "${ATOMS[@]}"
rules=0; "$BIN/java" -cp "$JAR$SEP$WORK/gen" M3DecoratorFill --rule-check "$SRC" "$WORK/rules.tsv" 2>/dev/null || rules=$?
{ printf '# SPDX-License-Identifier: Apache-2.0\n'; tr -d '\r' < "$WORK/rules.tsv"; } > "$Q/RULE_CHECKS.tsv"
echo "M3_DECORATOR_FILL stage=rule-check exit=$rules"
printf 'm3_class\tsignature\tcategory\temitted_or_reason\n' > "$Q/METHOD_ATOMS.tsv"
echo "M3_DECORATOR_FILL stage=fill"
awk -F'\t' 'NR > 1 && $1 ~ /^apache-/ && $3 ~ /\.M3(Unmodifiable|Predicated|Transformed|Synchronized|FixedSize|Lazy|Growth|Defaulted|Composite|CollectionBag|CollectionSortedBag)/ { print $1 "\t" $2 "\t" $3 }' "$S" |
while IFS=$'\t' read -r mod fqn m3; do
	f="$I/$mod/src/main/java/${m3//.//}.java"
	git show "$SCAFFOLD_REV:$f" > "$WORK/scaffold.java"
	rc=0; "$BIN/java" -cp "$JAR$SEP$WORK/gen" M3DecoratorFill "$SRC" "$WORK/scaffold.java" "$fqn" "$WORK/out/${m3##*.}.java" "$WORK/atoms.tsv" 2>/dev/null || rc=$?
	[ "$rc" -eq 0 ] && cp "$WORK/out/${m3##*.}.java" "$f" && echo "$f" >> "$WORK/filled.txt" && readme "$mod" "$fqn" "$m3"
	[ "$rc" -eq 0 ] || [ "$rc" -eq 3 ] || { echo "M3_DECORATOR_FILL_FAIL $m3 exit=$rc"; exit 2; }
done
tr -d '\r' < "$WORK/atoms.tsv" | LC_ALL=C sort >> "$Q/METHOD_ATOMS.tsv"
echo "M3_DECORATOR_FILL stage=compile classes=$(wc -l < "$WORK/filled.txt")"
"$BIN/javac" -Xlint:all -Werror -proc:none -cp "$JAR" -d "$WORK/cls" $(cat "$WORK/filled.txt")
"$BIN/javac" -proc:none -cp "$JAR$SEP$WORK/cls" -d "$WORK/hcls" "$Q/M3DecoratorDifferential.java" "$Q/M3SyncProbe.java" "$Q/M3LockTraceProbe.java" \
	"$Q/M3PredicatedProbe.java" "$Q/M3Mutant.java" 2>&1 | grep -v -e '^Note:' -e 'deprecat' || true
printf 'm3_class\toracle\tbacking\tfactory\tpolicy\tresult\n' > "$Q/DIFFERENTIAL.tsv"; : > "$WORK/mismatch.tsv"; fail=0
[ "$rules" -eq 0 ] || fail=1
printf 'm3_class\tprobe\tbacking\tpolicy\tresult\n' > "$Q/PROBES.tsv"
CP="$JAR$SEP$WORK/cls$SEP$WORK/hcls"
while IFS=$'\t' read -r m3 oracle backing factory probe policy; do
	[ "$m3" = m3_class ] && continue
	policy="${policy:--}"; policy="${policy%$'\r'}"
	rc=0; line=$("$BIN/java" -cp "$CP" M3DecoratorDifferential "$m3" "$oracle" "$backing" "$factory" "$WORK/mismatch.tsv" "$policy" 2>&1 | grep -o 'M3_DECORATOR_DIFF.*') || rc=$?
	printf '%s\t%s\t%s\t%s\t%s\t%s\n' "$m3" "$oracle" "$backing" "$factory" "$policy" "${line#M3_DECORATOR_DIFF }" >> "$Q/DIFFERENTIAL.tsv"
	echo "M3_DECORATOR_FILL stage=differential ${m3##*.} $backing $policy exit=$rc"
	[ "$rc" -eq 0 ] || fail=1
	# SYNC family: which calls take the monitor (M3SyncProbe) and whether each backing call runs inside it (M3LockTraceProbe).
	# PREDICATED family: view sweep, MapIterator/ListIterator scripts and serialization order (M3PredicatedProbe).
	case "$probe" in sync) probes="M3SyncProbe M3LockTraceProbe";; predicated) probes="M3PredicatedProbe";; *) probes="";; esac
	for p in $probes; do
		prc=0; out=$("$BIN/java" -cp "$CP" "$p" "$m3" "$oracle" "$backing" "$factory" "$WORK/mismatch.tsv" "$policy" 2>&1 | tr -d '\r' | tail -1) || prc=$?
		printf '%s\t%s\t%s\t%s\t%s\n' "$m3" "$p" "$backing" "$policy" "exit=$prc ${out:0:200}" >> "$Q/PROBES.tsv"
		[ "$prc" -eq 0 ] || fail=1
	done
done < "$Q/TARGETS.tsv"
# Negative controls: each spec id is planted into a copy of its target (generated class or generator) and its check must FAIL.
echo "M3_DECORATOR_FILL stage=negative-controls"
printf 'id\trefutation\ttarget\tcheck\tbacking\tpolicy\tresult\tevidence\n' > "$Q/NEGATIVE_CONTROLS.tsv"
grep -v -e '^#' -e $'^id\t' "$Q/NEGATIVE_CONTROLS_SPEC.tsv" | tr -d '\r' | cut -f1,2,3,6-9 | awk -F'\t' '!seen[$1]++' |
while IFS=$'\t' read -r id ref target check backing policy expect; do
	d="$WORK/nc/$id"; mkdir -p "$d/cls"; ev=""; caught=MISSED; crc=0
	if [ "$target" = GENERATOR ]; then
		src="$Q/M3DecoratorFill.java"; out="$d/M3DecoratorFill.java"; with=("${ATOMS[@]}")
	else
		src=$(grep "/$target.java\$" "$WORK/filled.txt"); out="$d/$target.java"; with=()
	fi
	if "$BIN/java" -cp "$WORK/hcls" M3Mutant "$Q/NEGATIVE_CONTROLS_SPEC.tsv" "$id" "$src" "$out" 2>/dev/null; then
		"$BIN/javac" -proc:none -cp "$JAR" -d "$d/cls" "$out" "${with[@]}" 2>&1 | grep -v -e '^Note:' || true
		if [ "$check" = rulecheck ]; then
			"$BIN/java" -cp "$JAR$SEP$d/cls" M3DecoratorFill --rule-check "$SRC" "$d/rules.tsv" 2>/dev/null || crc=$?
			[ -f "$d/rules.tsv" ] || : > "$d/rules.tsv"
			ev=$(awk -F'\t' -v e="$expect" '$1 == e { print $1 " expected=" $5 " actual=" $6 " " $7 }' "$d/rules.tsv")
			[ "$crc" -ne 0 ] && [ -n "$(awk -F'\t' -v e="$expect" '$1 == e && $7 == "FAIL"' "$d/rules.tsv")" ] && caught=CAUGHT
		else
			IFS=$'\t' read -r noracle nfactory < <(awk -F'\t' -v m="com.m3.collections.apache.$target" -v b="$backing" -v p="$policy" \
				'$1 == m && $3 == b && $6 == p { print $2 "\t" $4; exit }' "$Q/TARGETS.tsv" | tr -d '\r')
			main=M3DecoratorDifferential; [ "$check" = probe ] && main=M3PredicatedProbe
			"$BIN/java" -cp "$JAR$SEP$d/cls$SEP$WORK/cls$SEP$WORK/hcls" "$main" "com.m3.collections.apache.$target" "$noracle" "$backing" "$nfactory" \
				"$d/mismatch.tsv" "$policy" > "$d/log.txt" 2>&1 || crc=$?
			ev="exit=$crc $(grep -o 'mismatches=[0-9]*' "$d/log.txt" | tail -1); first: $(head -1 "$d/mismatch.tsv" 2>/dev/null | cut -f2- | tr '\t' ' ' | cut -c1-160)"
			[ "$crc" -eq 4 ] && caught=CAUGHT
		fi
	else
		ev="mutant site count is not 1"
	fi
	printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$id" "$ref" "$target" "$check" "$backing" "$policy" "$caught" "$ev" >> "$Q/NEGATIVE_CONTROLS.tsv"
	echo "M3_DECORATOR_FILL stage=negative-control $id $caught"
	[ "$caught" = CAUGHT ] || touch "$WORK/nc-missed"
done
[ -e "$WORK/nc-missed" ] && fail=1
tr -d '\r' < "$WORK/mismatch.tsv" > "$Q/MISMATCHES.tsv"
filled=$(wc -l < "$WORK/filled.txt"); atoms=$(($(wc -l < "$Q/METHOD_ATOMS.tsv") - 1)); manual=$(grep -c $'\tMANUAL\t' "$Q/METHOD_ATOMS.tsv" || true)
targets=$(($(wc -l < "$Q/DIFFERENTIAL.tsv") - 1)); mism=$(wc -l < "$Q/MISMATCHES.tsv"); verdict=$([ "$fail" -eq 0 ] && echo PASS || echo FAIL)
probes=$(($(wc -l < "$Q/PROBES.tsv") - 1)); ncs=$(($(wc -l < "$Q/NEGATIVE_CONTROLS.tsv") - 1)); caught=$(grep -c $'\tCAUGHT\t' "$Q/NEGATIVE_CONTROLS.tsv" || true)
rulechecks=$(grep -c $'\t\(PASS\|FAIL\)$' "$Q/RULE_CHECKS.tsv" || true); rulefail=$(grep -c $'\tFAIL$' "$Q/RULE_CHECKS.tsv" || true)
# M3-SCALE section 5 output contract: STATUS, RUN_CONTEXT, PROVENANCE, VERIFY_CONTRACT, OUTPUT_CONTRACT, FINAL_REPORT.
sha() { sha256sum "$1" | cut -c1-64; }
printf 'stage\tstatus\tevidence\nrule_check\t%s\tchecks=%s fail=%s\nfill\tDONE\tfilled=%s atoms=%s manual=%s\ncompile\tDONE\tjavac -Xlint:all -Werror over %s classes\ndifferential\t%s\ttargets=%s probes=%s mismatches=%s\nnegative_controls\t%s\tcontrols=%s caught=%s\n' \
	"$([ "$rulefail" -eq 0 ] && echo PASS || echo FAIL)" "$rulechecks" "$rulefail" "$filled" "$atoms" "$manual" "$filled" "$verdict" "$targets" "$probes" "$mism" \
	"$([ "$caught" -eq "$ncs" ] && echo PASS || echo FAIL)" "$ncs" "$caught" > "$Q/STATUS.tsv"
printf 'key\tvalue\nscaffold_rev\t%s\njava\t%s\nrun_mode\tapply\nshards\t1\n' "$SCAFFOLD_REV" "$("$BIN/java" -version 2>&1 | head -1 | tr -d '\r"')" > "$Q/RUN_CONTEXT.tsv"
printf 'input\tsha256\nM3DecoratorFill.java\t%s\nM3DecoratorTemplates.java\t%s\nM3DecoratorJdkStandard.java\t%s\nM3DecoratorRuleCheck.java\t%s\nM3DecoratorDifferential.java\t%s\nM3PredicatedProbe.java\t%s\nNEGATIVE_CONTROLS_SPEC.tsv\t%s\ncommons-collections4-4.5.0.jar\t%s\nTARGETS.tsv\t%s\n' \
	"$(sha "$Q/M3DecoratorFill.java")" "$(sha "${ATOMS[0]}")" "$(sha "${ATOMS[1]}")" "$(sha "${ATOMS[2]}")" "$(sha "$Q/M3DecoratorDifferential.java")" "$(sha "$Q/M3PredicatedProbe.java")" "$(sha "$Q/NEGATIVE_CONTROLS_SPEC.tsv")" \
	"$(sha "$JAR")" "$(sha "$Q/TARGETS.tsv")" > "$Q/PROVENANCE.tsv"
printf 'order\tgate\tresult\n1\tdiff (git diff --check, run by the committer)\tEXTERNAL\n2\tlinter (javac -Xlint:all -Werror)\tPASS\n3\tcompile\tPASS\n4\ttests (M3DecoratorDifferential + probes + rule checks + negative controls)\t%s\n5\truntime\tNOT_REQUESTED\n' "$verdict" > "$Q/VERIFY_CONTRACT.tsv"
printf '# Final report: decorator fill\n\n- Files changed: %s owned decorator classes and their README files (listed in OUTPUT_CONTRACT.tsv).\n- Delta: %s method atoms classified, %s left as MANUAL residue; scaffold bodies replaced only in classes with no MANUAL atom.\n- Verification: javac -Xlint:all -Werror passed; rule checks %s/%s pass; differential %s, %s targets, %s probe runs, %s mismatches; negative controls %s/%s caught.\n- Blockers: the %s MANUAL atoms in METHOD_ATOMS.tsv (next families in PATTERNS.tsv).\n' \
	"$filled" "$atoms" "$manual" "$((rulechecks - rulefail))" "$rulechecks" "$verdict" "$targets" "$probes" "$mism" "$caught" "$ncs" "$manual" > "$Q/FINAL_REPORT.md"
{ printf 'artifact\tsha256\n'; for f in $(cat "$WORK/filled.txt") STATUS.tsv RUN_CONTEXT.tsv PROVENANCE.tsv VERIFY_CONTRACT.tsv FINAL_REPORT.md METHOD_ATOMS.tsv DIFFERENTIAL.tsv PROBES.tsv RULE_CHECKS.tsv NEGATIVE_CONTROLS.tsv MISMATCHES.tsv; do
	p="$f"; [ -f "$p" ] || p="$Q/$f"; printf '%s\t%s\n' "$f" "$(sha "$p")"; done; } > "$Q/OUTPUT_CONTRACT.tsv"
echo "M3_DECORATOR_FILL filled=$filled atoms=$atoms manual=$manual rule_checks=$rulechecks rule_fail=$rulefail targets=$targets probes=$probes mismatches=$mism negative_controls=$ncs caught=$caught verdict=$verdict"
exit "$fail"
