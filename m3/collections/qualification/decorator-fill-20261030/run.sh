# Pattern DECORATOR_FILL v1.1 driver: regenerate every five-provider decorator scaffold through M3DecoratorFill and
# write the fully classified ones back into their modules (MANUAL atoms keep the scaffold). Then compile them with
# -Xlint:all -Werror and run M3DecoratorDifferential against Apache Commons Collections 4.5.0 for each TARGETS.tsv row.
# Ledgers: METHOD_ATOMS.tsv (one row per method atom), DIFFERENTIAL.tsv (one row per proven class), MISMATCHES.tsv.
# Usage (repository root): bash m3/collections/qualification/decorator-fill-20261030/run.sh <commons-collections4-4.5.0.jar>
#   <unpacked commons-collections4-4.5.0-sources dir> [work dir]
# JAVA_HOME must be a JDK 21. Exit 0 = every target compiled and showed no mismatch.
set -euo pipefail
JAR="$1"; SRC="$2"; WORK="${3:-${TMPDIR:-/tmp}/m3-decorator-fill}"
# Scaffolds are read from this revision (the five-provider scaffold as generated), so reruns are idempotent.
SCAFFOLD_REV="${SCAFFOLD_REV:-bb66a8c16642a4e898dbc5fc7c3af0d5ed572136}"
Q=m3/collections/qualification/decorator-fill-20261030; I=m3/collections/implementations
S=m3/collections/qualification/five-provider-inventory-20261018/SCAFFOLD_SURFACE.tsv
BIN="$JAVA_HOME/bin"; SEP=":"; case "$(uname -s)" in MINGW*|MSYS*|CYGWIN*) SEP=";";; esac
readme() {
	cat > "$I/$1/README.md" <<EOF
<!-- SPDX-License-Identifier: Apache-2.0 -->
<!-- GENERATED by $Q/run.sh (pattern DECORATOR_FILL v1.1); regenerate, do not hand-edit. -->
# OWNED: ${3##*.}

\`$3\` is an owned decorator with the public contract of \`$2\` (Apache Commons Collections 4.5.0, Apache-2.0).
It holds one reference to the decorated owner; elements are never copied and no Entry or Node object is stored.

The bodies are generated by \`$Q/M3DecoratorFill.java\` from the five-provider scaffold. Each method atom is classified
against the Commons class as THROW, DELEGATE, EQUALS, WRAP, DEFAULT or FACTORY and emitted from a template; no provider
implementation code is copied. Views use the JDK unmodifiable owners (\`java.util.Collections\`) or this class's own factory.

Proof: \`$Q/M3DecoratorDifferential.java\` runs a seeded reflective differential against the Commons class, with results in
\`$Q/DIFFERENTIAL.tsv\`. Atom rows are in \`$Q/METHOD_ATOMS.tsv\`.
EOF
}
rm -rf "$WORK" && mkdir -p "$WORK/gen" "$WORK/out" "$WORK/cls" "$WORK/hcls"
"$BIN/javac" -proc:none -cp "$JAR" -d "$WORK/gen" "$Q/M3DecoratorFill.java"
printf 'm3_class\tsignature\tcategory\temitted_or_reason\n' > "$Q/METHOD_ATOMS.tsv"
awk -F'\t' 'NR > 1 && $1 ~ /^apache-/ && $3 ~ /\.M3(Unmodifiable|Predicated|Transformed|Synchronized|FixedSize|Lazy|Growth|Defaulted|Composite|CollectionBag|CollectionSortedBag)/ { print $1 "\t" $2 "\t" $3 }' "$S" |
while IFS=$'\t' read -r mod fqn m3; do
	f="$I/$mod/src/main/java/${m3//.//}.java"
	git show "$SCAFFOLD_REV:$f" > "$WORK/scaffold.java"
	rc=0; "$BIN/java" -cp "$JAR$SEP$WORK/gen" M3DecoratorFill "$SRC" "$WORK/scaffold.java" "$fqn" "$WORK/out/${m3##*.}.java" "$WORK/atoms.tsv" 2>/dev/null || rc=$?
	[ "$rc" -eq 0 ] && cp "$WORK/out/${m3##*.}.java" "$f" && echo "$f" >> "$WORK/filled.txt" && readme "$mod" "$fqn" "$m3"
	[ "$rc" -eq 0 ] || [ "$rc" -eq 3 ] || { echo "M3_DECORATOR_FILL_FAIL $m3 exit=$rc"; exit 2; }
done
tr -d '\r' < "$WORK/atoms.tsv" | LC_ALL=C sort >> "$Q/METHOD_ATOMS.tsv"
"$BIN/javac" -Xlint:all -Werror -proc:none -cp "$JAR" -d "$WORK/cls" $(cat "$WORK/filled.txt")
"$BIN/javac" -proc:none -cp "$JAR$SEP$WORK/cls" -d "$WORK/hcls" "$Q/M3DecoratorDifferential.java"
printf 'm3_class\toracle\tbacking\tresult\n' > "$Q/DIFFERENTIAL.tsv"; : > "$WORK/mismatch.tsv"; fail=0
while IFS=$'\t' read -r m3 oracle backing; do
	[ "$m3" = m3_class ] && continue
	rc=0; line=$("$BIN/java" -cp "$JAR$SEP$WORK/cls$SEP$WORK/hcls" M3DecoratorDifferential "$m3" "$oracle" "$backing" "$WORK/mismatch.tsv" 2>&1 | grep -o 'M3_DECORATOR_DIFF.*') || rc=$?
	printf '%s\t%s\t%s\t%s\n' "$m3" "$oracle" "$backing" "${line#M3_DECORATOR_DIFF }" >> "$Q/DIFFERENTIAL.tsv"
	[ "$rc" -eq 0 ] || fail=1
done < "$Q/TARGETS.tsv"
tr -d '\r' < "$WORK/mismatch.tsv" > "$Q/MISMATCHES.tsv"
echo "M3_DECORATOR_FILL filled=$(wc -l < "$WORK/filled.txt") atoms=$(($(wc -l < "$Q/METHOD_ATOMS.tsv") - 1)) manual=$(grep -c $'\tMANUAL\t' "$Q/METHOD_ATOMS.tsv" || true) targets=$(($(wc -l < "$Q/DIFFERENTIAL.tsv") - 1)) mismatches=$(wc -l < "$Q/MISMATCHES.tsv")"
exit "$fail"
