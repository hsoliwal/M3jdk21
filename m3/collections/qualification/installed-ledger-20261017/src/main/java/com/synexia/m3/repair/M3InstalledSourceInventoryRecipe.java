package com.synexia.m3.repair;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.LinkOption;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.ArrayList;
import java.util.Collections;
import java.util.HexFormat;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import java.util.stream.Stream;

/**
 * Mechanical Maven receipt recipe: source-bound, path-complete collection inventory.
 * This never modifies historical manifests nor scans outside the owning module.
 */
public final class M3InstalledSourceInventoryRecipe {
    private M3InstalledSourceInventoryRecipe() { }

    public static String sha256(byte[] bytes) {
        try {
            return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(bytes));
        } catch (NoSuchAlgorithmException impossible) {
            throw new AssertionError(impossible);
        }
    }

    public static String digest(Path path) throws IOException {
        if (!Files.isRegularFile(path, LinkOption.NOFOLLOW_LINKS)) {
            throw new IllegalStateException("not an ordinary owned file: " + path);
        }
        return sha256(Files.readAllBytes(path));
    }

    public static String emit(Path repository, String sourceCommit) throws IOException {
        if (!sourceCommit.matches("[0-9a-f]{40}")) {
            throw new IllegalStateException("source revision must be exact Git commit SHA");
        }
        Path module = repository.resolve("m3/collections");
        if (!Files.isDirectory(module)) {
            throw new IllegalStateException("no installed M3 collections module");
        }
        List<Path> files = new ArrayList<>();
        for (String folder : List.of("src/main/java", "src/test/java")) {
            Path root = module.resolve(folder);
            if (!Files.isDirectory(root)) {
                throw new IllegalStateException("source tree absent: " + root);
            }
            try (Stream<Path> candidates = Files.walk(root)) {
                candidates.filter(p -> p.getFileName().toString().endsWith(".java"))
                        .forEach(files::add);
            }
        }
        for (String relative : List.of(
                "LICENSE", "NOTICE",
                "verification/PreparedLaneAllocationProbe.java",
                "verification/SegmentedLaneNativeProbe.java")) {
            files.add(module.resolve(relative));
        }
        List<String> sorted = new ArrayList<>();
        Set<String> names = new HashSet<>();
        int javaCount = 0;
        for (Path file : files) {
            if (Files.isSymbolicLink(file) || !file.toAbsolutePath().normalize()
                    .startsWith(module.toAbsolutePath().normalize())) {
                throw new IllegalStateException("unsafe source path: " + file);
            }
            String relative = repository.relativize(file).toString().replace('\\', '/');
            if (relative.contains("..") || !relative.startsWith("m3/collections/")
                    || !names.add(relative)) {
                throw new IllegalStateException("duplicate or unsafe source: " + relative);
            }
            if (relative.contains("/src/") && relative.endsWith(".java")) javaCount++;
            sorted.add(relative + "\t" + digest(file));
        }
        Collections.sort(sorted);
        if (javaCount != 131 || names.size() != 135) {
            throw new IllegalStateException("unexpected source member census: java="
                    + javaCount + " total=" + names.size()
                    + "; requalify recipe against observed inventory");
        }
        String header = "# SPDX-License-Identifier: Apache-2.0\n"
                + "# M3_INSTALLED_SOURCE_V3; source-commit=" + sourceCommit + "\n"
                + "# mechanically generated by M3InstalledSourceInventoryRecipe; historical manifests untouched\n"
                + "# path\tsha256\n";
        return header + String.join("\n", sorted) + "\n";
    }
}
