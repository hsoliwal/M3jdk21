package jdk.m3.collections;

import java.util.Arrays;
import java.util.Objects;

/**
 * Open-addressing long-to-byte map.
 *
 * <p>Storage is exactly one long[] key lane plus one byte[] value lane.
 * Key zero is represented by one collection-level flag/value so zero remains
 * available without a state object or per-bucket occupancy byte.
 *
 * <p>Lineage: absorbed from Synexia {@code m3-primitives/src/main/java/jdk/internal/m3/primitives/LongByteHashMap.java}
 * blob {@code 498a8b2989d50a04ccbed8c53ff156f0a5c11280} at com.synexia develop {@code 35474ccf8dafbe80feb55f1d82cb1136eeec119d} by
 * RELOCATE_M3_OWNER v3 (identifiers only, global M3 owner map; bytecode equal to the source modulo names).
 */
public final class LongByteHashMap {
    @FunctionalInterface
    public interface Consumer {
        void accept(long key, byte value);
    }

    private long[] keys;
    private byte[] values;
    private int mask;
    private int threshold;
    private int size;
    private boolean hasZero;
    private byte zeroValue;
    private final float loadFactor;

    public LongByteHashMap() {
        this(16, DenseHash.DEFAULT_LOAD_FACTOR);
    }

    public LongByteHashMap(int expected) {
        this(expected, DenseHash.DEFAULT_LOAD_FACTOR);
    }

    public LongByteHashMap(int expected, float loadFactor) {
        this.loadFactor = loadFactor;
        int capacity = DenseHash.capacityFor(expected, loadFactor);
        keys = new long[capacity];
        values = new byte[capacity];
        mask = capacity - 1;
        threshold = DenseHash.threshold(capacity, loadFactor);
    }

    public int size() { return size; }
    public boolean isEmpty() { return size == 0; }
    public int capacity() { return keys.length; }
    public long payloadBytes() { return (long) keys.length * Long.BYTES + values.length; }

    public void ensureCapacity(int expectedSize) {
        if (expectedSize < 0) throw new IllegalArgumentException("expectedSize < 0");
        int capacity = DenseHash.capacityFor(expectedSize, loadFactor);
        if (capacity > keys.length) rehash(capacity);
    }

    public boolean containsKey(long key) {
        return key == 0L ? hasZero : find(key) >= 0;
    }

    public byte get(long key) {
        if (key == 0L) return hasZero ? zeroValue : 0;
        int index = find(key);
        return index < 0 ? 0 : values[index];
    }

    public int getUnsigned(long key) {
        return Byte.toUnsignedInt(get(key));
    }

    public byte getOrDefault(long key, byte defaultValue) {
        if (key == 0L) return hasZero ? zeroValue : defaultValue;
        int index = find(key);
        return index < 0 ? defaultValue : values[index];
    }

    public byte put(long key, byte value) {
        if (key == 0L) {
            byte old = zeroValue;
            // Preserve tiny-load-factor growth on existing zero updates as well.
            // Prepare every replacement lane before publishing zero-key state.
            if (size + (hasZero ? 0 : 1) > threshold) rehash(keys.length << 1);
            if (!hasZero) {
                hasZero = true;
                size++;
            }
            zeroValue = value;
            return old;
        }

        int index = DenseHash.mix(key) & mask;
        long current;
        while ((current = keys[index]) != 0L) {
            if (current == key) {
                byte old = values[index];
                values[index] = value;
                return old;
            }
            index = (index + 1) & mask;
        }
        keys[index] = key;
        values[index] = value;
        if (++size > threshold) {
            try {
                // Keep the pending pair in its original slot during migration,
                // preserving collision-dependent traversal order after growth.
                rehash(keys.length << 1);
            } catch (OutOfMemoryError | NegativeArraySizeException failure) {
                keys[index] = 0L;
                values[index] = 0;
                size--;
                throw failure;
            }
        }
        return 0;
    }

    public byte putUnsigned(long key, int value) {
        if ((value & ~0xff) != 0) throw new IllegalArgumentException("value must be 0..255");
        return put(key, (byte) value);
    }

    public void putAll(long[] sourceKeys, byte[] sourceValues) {
        Objects.requireNonNull(sourceKeys, "sourceKeys");
        Objects.requireNonNull(sourceValues, "sourceValues");
        if (sourceKeys.length != sourceValues.length) {
            throw new IllegalArgumentException("key/value length mismatch");
        }
        ensureCapacity(size + sourceKeys.length);
        for (int i = 0; i < sourceKeys.length; i++) {
            put(sourceKeys[i], sourceValues[i]);
        }
    }

    public byte remove(long key) {
        if (key == 0L) {
            if (!hasZero) return 0;
            hasZero = false;
            size--;
            byte old = zeroValue;
            zeroValue = 0;
            return old;
        }

        int index = DenseHash.mix(key) & mask;
        long current;
        while ((current = keys[index]) != 0L) {
            if (current == key) {
                byte old = values[index];
                shiftKeys(index);
                size--;
                return old;
            }
            index = (index + 1) & mask;
        }
        return 0;
    }

    public void clear() {
        Arrays.fill(keys, 0L);
        Arrays.fill(values, (byte) 0);
        size = 0;
        hasZero = false;
        zeroValue = 0;
    }

    public void forEach(Consumer consumer) {
        Objects.requireNonNull(consumer, "consumer");
        if (hasZero) consumer.accept(0L, zeroValue);
        int remaining = size - (hasZero ? 1 : 0);
        for (int i = 0; remaining > 0 && i < keys.length; i++) {
            long key = keys[i];
            if (key != 0L) {
                consumer.accept(key, values[i]);
                remaining--;
            }
        }
    }

    private int find(long key) {
        int index = DenseHash.mix(key) & mask;
        long current;
        while ((current = keys[index]) != 0L) {
            if (current == key) return index;
            index = (index + 1) & mask;
        }
        return -1;
    }

    private void shiftKeys(int index) {
        for (;;) {
            int last = index;
            index = (index + 1) & mask;
            long current;
            while ((current = keys[index]) != 0L) {
                int slot = DenseHash.mix(current) & mask;
                if (last <= index ? last >= slot || slot > index : last >= slot && slot > index) break;
                index = (index + 1) & mask;
            }
            if (current == 0L) {
                keys[last] = 0L;
                values[last] = 0;
                return;
            }
            keys[last] = current;
            values[last] = values[index];
        }
    }

    private void rehash(int newCapacity) {
        long[] oldKeys = keys;
        byte[] oldValues = values;
        long[] nextKeys = new long[newCapacity];
        byte[] nextValues = new byte[newCapacity];
        int nextMask = newCapacity - 1;
        int nextThreshold = DenseHash.threshold(newCapacity, loadFactor);

        for (int i = 0; i < oldKeys.length; i++) {
            long key = oldKeys[i];
            if (key != 0L) {
                int index = DenseHash.mix(key) & nextMask;
                while (nextKeys[index] != 0L) index = (index + 1) & nextMask;
                nextKeys[index] = key;
                nextValues[index] = oldValues[i];
            }
        }
        // Publish both lanes and their metadata only after complete migration.
        keys = nextKeys;
        values = nextValues;
        mask = nextMask;
        threshold = nextThreshold;
    }
}
