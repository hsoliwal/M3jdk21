import java.util.function.Supplier;

/**
 * IContainer - Minimal IoC container (compile-time generated).
 *
 * <h2>IoC Philosophy</h2>
 * <blockquote>
 * "ContextOS must never {@code new} anything important."
 * Creation, lifecycle, and policy are inverted.
 * But IoC is COMPILE-TIME, not runtime.
 * </blockquote>
 *
 * <h2>IoC Priority Hierarchy</h2>
 * <pre>
 * 1. COMPILE-TIME WIRING (AnOP)
 *    Generated factories, static final references
 *    Inspired by: Dagger 2, Guice compile-time
 *
 * 2. INTERFACE + FACTORY (IOP)
 *    Factory methods returning interface types
 *    Inspired by: CDI producers, Spring @Bean
 *
 * 3. CONSTRUCTOR INJECTION (OOP)
 *    All dependencies via constructor
 *    Inspired by: Clean architecture
 *
 * X. RUNTIME REFLECTION (FORBIDDEN)
 *    No classpath scanning
 *    No field injection via reflection
 *    No dynamic proxy for semantics
 * </pre>
 *
 * <h2>Usage</h2>
 * <pre>{@code
 * // Container is compile-time generated
 * IContainer container = ContextOS$Container.INSTANCE;
 *
 * // Get typed service
 * IContextKernel kernel = container.get(IContextKernel.class);
 *
 * // Get with qualifier
 * IMemoryAdapter adapter = container.get(IMemoryAdapter.class, "sqlite");
 * }</pre>
 *
 * <h2>Generated Implementation Pattern</h2>
 * <pre>{@code
 * // Generated by AnOP Processor - DO NOT EDIT
 * public final class ContextOS$Container implements IContainer {
 *
 *     private static final IMemoryAdapter MEMORY =
 *         new CompositeMemoryAdapter<>(
 *             new LocalCacheAdapter<>(10_000),
 *             new SqliteMemoryAdapter(Path.of("contextos"))
 *         );
 *
 *     @Override
 *     public <T> T get(Class<T> type) {
 *         return switch (type.getName()) {
 *             case "IMemoryAdapter" -> (T) MEMORY;
 *             default -> throw new IllegalArgumentException(type.getName());
 *         };
 *     }
 * }
 * }</pre>
 *
 * @since ContextOS 1.0 - Compile-Time IoC
 */
@ISpec(
    value = "Minimal IoC Container - compile-time generated dependency injection",
    constraints = {
        "COMPILE-TIME wiring only, no runtime reflection",
        "Priority: AnOP generated > Interface+Factory > Constructor injection",
        "FORBIDDEN: classpath scanning, field injection, dynamic proxy",
        "Container is compile-time generated, not runtime configured"
    },
    invariants = {
        "get(type) returns singleton of specified type",
        "get(type, qualifier) returns qualified instance",
        "contains(type) returns true if type is registered"
    },
    examples = {
        "IContextKernel kernel = container.get(IContextKernel.class)",
        "IMemoryAdapter adapter = container.get(IMemoryAdapter.class, \"sqlite\")"
    },
    model = Model.ModelType.SONNET,
    stability = Stability.Level.STABLE
)
/**
 * <p>Lineage: absorbed from Synexia {@code m3-cop/src/main/java/jdk/internal/m3/context/factory/IContainer.java}
 * blob {@code 480bb95e9c36a5d671e84b7179a3dd3b70394282} at com.synexia develop {@code 8ab80ea57d9f} by
 * RELOCATE_M3_OWNER v4 (paradigm COP batch 2 (jdk.m3.paradigm, context) v6.3: identifiers and package only; bytecode equal to the source modulo names).
 */
public interface IContainer {

    // --- CORE RESOLUTION ---

    /**
     * Get a service by type.
     *
     * @param <T>  the service type
     * @param type the service class
     * @return the service instance
     * @throws IllegalArgumentException if type not bound
     */
    <T> T get(Class<T> type);

    /**
     * Get a service by type with qualifier.
     *
     * @param <T>       the service type
     * @param type      the service class
     * @param qualifier the qualifier name
     * @return the service instance
     * @throws IllegalArgumentException if type/qualifier not bound
     */
    default <T> T get(Class<T> type, String qualifier) {
        return get(type); // Default ignores qualifier
    }

    /**
     * Try to get a service (optional resolution).
     *
     * @param <T>  the service type
     * @param type the service class
     * @return optional containing service if bound
     */
    default <T> Optional<T> tryGet(Class<T> type) {
        try {
            return Optional.of(get(type));
        } catch (IllegalArgumentException e) {
            return Optional.empty();
        }
    }

    // --- BINDING (For testing/configuration only - compile-time preferred) ---

    /**
     * Bind a type to a supplier.
     * <p>
     * Note: Prefer compile-time wiring via AnOP processors.
     * Runtime binding should only be used for testing.
     *
     * @param <T>      the service type
     * @param type     the service class
     * @param supplier the supplier
     */
    default <T> void bind(Class<T> type, Supplier<T> supplier) {
        throw new UnsupportedOperationException(
            "Compile-time container does not support runtime binding");
    }

    /**
     * Bind a type instance.
     *
     * @param <T>      the service type
     * @param type     the service class
     * @param instance the instance
     */
    default <T> void bindInstance(Class<T> type, T instance) {
        bind(type, () -> instance);
    }

    // --- SCOPE MANAGEMENT ---

    /**
     * Create a child container (hierarchical scope).
     *
     * @return child container that delegates to parent for unbound types
     */
    default IContainer createChild() {
        IContainer parent = this;
        return new IContainer() {
            private final java.util.Map<Class<?>, Object> bindings =
                new java.util.concurrent.ConcurrentHashMap<>();

            @Override
            public <T> T get(Class<T> type) {
                @SuppressWarnings("unchecked")
                T local = (T) bindings.get(type);
                return local != null ? local : parent.get(type);
            }

            @Override
            public <T> void bind(Class<T> type, Supplier<T> supplier) {
                bindings.put(type, supplier.get());
            }
        };
    }
}
