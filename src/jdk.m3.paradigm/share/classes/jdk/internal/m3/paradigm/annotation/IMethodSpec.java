package jdk.internal.m3.paradigm.annotation;

import java.lang.annotation.Documented;
import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * IMethodSpec - Method-level specification for LLM code generation.
 *
 * <h2>Purpose</h2>
 *
 * <p>
 * Annotates methods to specify their behavior, contracts, and invariants for
 * LLM-based code generation. Similar to {@link ISpec} but at method
 * granularity.
 *
 * <h2>Usage</h2>
 *
 * <pre>{@code
 * public class MathOps {
 *
 * 	@IMethodSpec(value = "Calculate factorial of n using iterative approach", constraints = {"Must handle n=0 as 1",
 * 			"Must use long to avoid overflow up to n=20", "Must throw for negative inputs"}, invariants = {
 * 					"Result always >= 1", "factorial(0) == 1", "factorial(n) == n * factorial(n-1)"}, examples = {
 * 							"factorial(0) → 1", "factorial(5) → 120",
 * 							"factorial(-1) → IllegalArgumentException"}, preconditions = {"n >= 0",
 * 									"n <= 20"}, postconditions = {"result > 0", "result == expected_factorial(n)"})
 * 	public static long factorial(int n) {
 * 		// Implementation generated by LLM
 * 	}
 * }
 * }</pre>
 *
 * <h2>Design by Contract</h2>
 *
 * <ul>
 * <li><strong>Preconditions</strong> - Conditions that must hold before method
 * execution
 * <li><strong>Postconditions</strong> - Conditions that must hold after method
 * execution
 * <li><strong>Invariants</strong> - Properties that always hold for the method
 * <li><strong>Side effects</strong> - Observable state changes caused by the
 * method
 * </ul>
 *
 * <h2>Generation Process</h2>
 *
 * <pre>
 * 1. Scan methods annotated with @IMethodSpec
 * 2. Generate precondition checks at method entry
 * 3. Generate implementation body from constraints
 * 4. Generate postcondition assertions before return
 * 5. Generate test cases covering all examples
 * 6. Verify invariants hold for all test cases
 * </pre>
 *
 * <h2>Method Categories</h2>
 *
 * <ul>
 * <li><strong>Pure functions</strong> - No side effects, deterministic
 * <li><strong>Procedures</strong> - Side effects expected
 * <li><strong>Factory methods</strong> - Object creation contracts
 * <li><strong>Validators</strong> - Boolean return with specific semantics
 * <li><strong>Transformers</strong> - Input → Output mapping contracts
 * </ul>
 *
 * @see ISpec
 * @see IFieldSpec
 * @see IParamSpec
 * @see Stability
 * @since Phase 1
 *
 * <p>Lineage: absorbed from Synexia {@code m3-anop/src/main/java/jdk/internal/m3/anop/IMethodSpec.java}
 * blob {@code 4df72a398f6b70e63b00e7077374db60378d7438} at com.synexia develop {@code 8ab80ea57d9f} by
 * RELOCATE_M3_OWNER v4 (paradigm AnOP LazyInit batch (jdk.m3.paradigm, annotation) v6.3: identifiers and package only; bytecode equal to the source modulo names).
 */
@Target(ElementType.METHOD)
@Retention(RetentionPolicy.SOURCE)
@Documented
public @interface IMethodSpec {

    // --- SPECIFICATION ---

    /**
     * Natural language description of the method behavior and purpose.
     *
     * @return method description
     */
    String value();

    /**
     * Constraints that guide generation (soft requirements). These influence the
     * implementation.
     *
     * @return constraint descriptions
     */
    String[] constraints() default {};

    /**
     * Invariants that MUST hold (hard requirements). These become assertions.
     *
     * @return invariant expressions
     */
    String[] invariants() default {};

    /**
     * Example input/output pairs. Format: "method(args) → expected_result"
     *
     * @return example pairs
     */
    String[] examples() default {};

    // --- DESIGN BY CONTRACT ---

    /**
     * Preconditions that must hold before method execution. Checked at method
     * entry.
     *
     * @return precondition expressions
     */
    String[] preconditions() default {};

    /**
     * Postconditions that must hold after method execution. Checked before return.
     *
     * @return postcondition expressions
     */
    String[] postconditions() default {};

    /**
     * Side effects caused by this method. Empty array means pure function.
     *
     * @return side effect descriptions
     */
    String[] sideEffects() default {};

    /**
     * Exceptions that can be thrown and their conditions.
     *
     * @return exception specifications (format: "ExceptionType: condition")
     */
    String[] throws_() default {};

    // --- COMPLEXITY & PERFORMANCE ---

    /**
     * Time complexity in Big-O notation.
     *
     * @return time complexity (e.g., "O(n)", "O(log n)")
     */
    String timeComplexity() default "";

    /**
     * Space complexity in Big-O notation.
     *
     * @return space complexity (e.g., "O(1)", "O(n)")
     */
    String spaceComplexity() default "";

    /**
     * Maximum execution time in milliseconds. 0 means no limit.
     *
     * @return max execution time
     */
    long maxExecutionTimeMs() default 0;

    // --- MODEL SELECTION ---

    /**
     * Preferred model for generation.
     *
     * @return model type (default: SONNET)
     */
    Model.ModelType model() default Model.ModelType.SONNET;

    /**
     * Fallback model if preferred is unavailable.
     *
     * @return fallback model type
     */
    Model.ModelType fallback() default Model.ModelType.OLLAMA;

    /**
     * Maximum tokens for generation. 0 means use model default.
     *
     * @return max tokens
     */
    int maxTokens() default 0;

    /**
     * Temperature for generation (0.0-1.0). -1 means use model default.
     *
     * @return temperature
     */
    double temperature() default -1.0;

    // --- STABILITY & QUALITY ---

    /**
     * Target stability level for generated implementation.
     *
     * @return stability level
     */
    Stability.Level stability() default Stability.Level.ALPHA;

    /**
     * Test class to verify generated implementation.
     *
     * @return test class (Void.class = no test)
     */
    Class<?> test() default Void.class;

    /**
     * Maximum generation attempts before failing.
     *
     * @return max retries (default: 3)
     */
    int maxRetries() default 3;
}
