package jdk.internal.m3.paradigm.annotation;

import java.lang.annotation.Documented;
import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * LazyInit - Defers bean initialization until first use.
 *
 * <h2>From Spring Framework</h2>
 *
 * <pre>
 *
 * {
 *     &#64;code
 *     &#64;Component
 *     &#64;LazyInit
 *     public class ExpensiveService {
 *         // Not instantiated until first request
 *     }
 *
 *     &#64;Autowired
 *     {@code @LazyInit}
 *     private ExpensiveService service;
 * }
 * </pre>
 *
 * @since ContextOS 1.0 - AnOP Spring
 *
 * <p>Lineage: absorbed from Synexia {@code m3-anop/src/main/java/jdk/internal/m3/anop/Lazy.java}
 * blob {@code 701afc9994c22a3425e8c4c6ce2920a451c13617} at com.synexia develop {@code 8ab80ea57d9f} by
 * RELOCATE_M3_OWNER v4 (paradigm AnOP LazyInit batch (jdk.m3.paradigm, annotation) v6.3: identifiers and package only; bytecode equal to the source modulo names).
 */
@Target({ElementType.TYPE, ElementType.METHOD, ElementType.CONSTRUCTOR, ElementType.PARAMETER, ElementType.FIELD})
@Retention(RetentionPolicy.SOURCE) // IOP: Compile-time only
@Documented
public @interface LazyInit {

    /**
     * Whether lazy initialization should apply.
     *
     * @return true for lazy init
     */
    boolean value() default true;
}
